#!/usr/bin/env bash
# Generate editors/helix/runtime/queries/nomi/ and set up Helix for Nomi.
#
#   scripts/sync-helix-runtime.sh          regenerate the query mirrors only
#   scripts/sync-helix-runtime.sh --check  fail if the mirrors are not current
#   scripts/sync-helix-runtime.sh --dev    regenerate, run `nomi editor install
#                                          helix` from this checkout, then
#                                          link the query directories to this
#                                          checkout, so query changes need no
#                                          reinstall
#
# A snapshot install is `nomi editor install helix` (internal/editors),
# which `make install-helix` runs from this checkout.
# TestHelixAndNeovimQueriesAreGenerated (internal/docscheck) runs --check.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HELIX_NOMI="$ROOT/editors/helix"
QUERY_DIR="$HELIX_NOMI/runtime/queries/nomi"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
USER_HELIX="$CONFIG_HOME/helix"

mode="${1:-}"
case "$mode" in
  "" | --check | --dev) ;;
  *) echo "usage: scripts/sync-helix-runtime.sh [--check | --dev]" >&2; exit 2 ;;
esac

# --check generates into a temporary directory and compares.
out="$QUERY_DIR"
if [[ "$mode" == "--check" ]]; then
  out="$(mktemp -d "${TMPDIR:-/tmp}/nomi-helix-check.XXXXXX")"
  trap 'rm -rf "$out"' EXIT
fi

mkdir -p "$out"
cp "$ROOT/tree-sitter-nomi/queries/injections.scm" "$out/injections.scm"
python3 - "$ROOT" "$out/highlights.scm" <<'PY'
import pathlib
import sys

root = pathlib.Path(sys.argv[1])
target = pathlib.Path(sys.argv[2])

# Helix applies overlapping captures in last-wins order, like Zed. Keep the
# Helix copy ordered from catch-alls to specifics, but translate Zed/source
# scopes to names that Helix's bundled themes style consistently.
text = (root / "editors/zed/languages/nomi/highlights.scm").read_text()
# Zed's own generated-by paragraph gives way to this generator's.
zed_header, sep, text = text.partition("\n\n")
if not sep or not zed_header.startswith("; GENERATED by scripts/sync-zed-highlights.sh "):
    sys.exit("sync-helix-runtime: editors/zed/languages/nomi/highlights.scm does not start with its generator's header; update the generator")
text = (
    "; GENERATED by scripts/sync-helix-runtime.sh from editors/zed/languages/nomi/highlights.scm.\n"
    "; Do not edit; change the source and run `make build-helix`.\n\n"
) + text
text = text.replace("@property", "@variable.other.member")
text = text.replace("@number", "@constant.numeric")
text = text.replace("@module", "@namespace")
text = text.replace("(codepoint) @string.special", "(codepoint) @constant.character")
text = text.replace(
    '(string_interpolation\n  ".{" @punctuation.special\n  "}" @punctuation.special)',
    '(string_interpolation\n  ".{" @constant.character.escape\n  "}" @constant.character.escape)',
)
text = text.replace("Zed's query priority", "Helix's query priority")
text = text.replace("Zed's last-wins priority", "Helix's last-wins priority")
text = text.replace("Zed layers semantic tokens", "editors layer semantic tokens")
target.write_text(text)
PY

case "$mode" in
  "") echo "Synced Helix Nomi runtime in $HELIX_NOMI"; exit 0 ;;
  --check)
    status=0
    for f in injections.scm highlights.scm; do
      if ! cmp -s "$out/$f" "$QUERY_DIR/$f"; then
        echo "sync-helix-runtime: editors/helix/runtime/queries/nomi/$f is not current; run make build-helix" >&2
        status=1
      fi
    done
    exit "$status"
    ;;
esac

# --dev: install as a user would, from this checkout, then replace the
# copied queries with links to it. nomi-catalog is the language of a
# module's phrase catalogs, whose queries inherit Helix's TOML ones.
go run -C "$ROOT" ./cmd/nomi editor install helix
for lang in nomi nomi-catalog; do
  user_dir="$USER_HELIX/runtime/queries/$lang"
  rm -rf "$user_dir"
  ln -s "$HELIX_NOMI/runtime/queries/$lang" "$user_dir"
done
echo "Linked Helix's queries in $USER_HELIX/runtime/queries to $HELIX_NOMI/runtime/queries"

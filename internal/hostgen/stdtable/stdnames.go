package stdtable

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"

	"github.com/nomi-language/nomi/internal/analysis"
	"github.com/nomi-language/nomi/std"
)

// StdNamesFile is where GenerateFiles writes the std names a capability
// list may hold, from internal/stdlibadapters, where `go generate` runs.
const StdNamesFile = "../capability/std_names_gen.go"

// stdNamesSource renders internal/capability's list of the std names a
// capability list may hold: `std::` and each std module a program can
// import, as the import writes it, sorted. A module that reaches nothing
// outside the machine is among them, as nomi.toml's lists accept it:
// allowing one allows nothing. internal/capability holds the list so that
// a runner that links no front end (vmrunner, the wasip1 reactor) checks a
// host's names against the same modules nomi.toml's lists are checked
// against.
func stdNamesSource() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by `go generate ./internal/stdlibadapters`; DO NOT EDIT.\n")
	b.WriteString("// Source: the std modules a program can import (std/*.nomi).\n\n")
	b.WriteString("package capability\n\n")
	b.WriteString("// stdNames is every std name a list may hold, sorted (UnknownStdName).\n")
	var names []string
	for _, m := range std.Shared().ModuleNames() {
		if _, internal := analysis.InternalStdModule(m); internal || m == "prelude" {
			continue
		}
		names = append(names, "std::"+strings.ReplaceAll(m, "/", "::"))
	}
	slices.Sort(names)
	b.WriteString("var stdNames = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// out answers the name of a method `func (b *bound) NAME(v T) (rt.Value, error)`.
func (g *Generator) out(s *Shape, t Type) (string, error) {
	key := "out|" + shapeKey(s) + "|" + t.String() + "|" + t.PkgPath()
	if m, ok := g.memo[key]; ok {
		return m, nil
	}
	goT, err := g.typ(t)
	if err != nil {
		return "", err
	}
	name := g.fresh("out")
	g.memo[key] = name
	var w bytes.Buffer
	fmt.Fprintf(&w, "// %s builds a %s from Go %s.\nfunc (b *bound) %s(v %s) (rt.Value, error) {\n", name, s, goT, name, goT)
	switch {
	case isScalar(s):
		x, fallible, err := g.widen(s, t, "v")
		if err != nil {
			return "", err
		}
		if fallible {
			fmt.Fprintf(&w, "\tx, err := %s\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn x, nil\n", x)
		} else {
			fmt.Fprintf(&w, "\treturn %s, nil\n", x)
		}
	case s.Kind == SUnit:
		w.WriteString("\treturn rt.Unit{}, nil\n")
	case isRtGeneric(t, "Maybe", "Result", "List", "Map"):
		if err := g.outRtGeneric(&w, s, t); err != nil {
			return "", err
		}
	case s.Kind == SMap && t.Kind() == reflect.Map && g.handles[TypeKey(t)] == "":
		// A Go map becomes an rt.Map[any, any] over the VM's own hash and
		// equality, as a Map literal's is; Go's iteration order does not
		// reach the Nomi value, whose order is the map's.
		kout, err := g.out(s.Elems[0], t.Key())
		if err != nil {
			return "", fmt.Errorf("key: %w", err)
		}
		vout, err := g.out(s.Elems[1], t.Elem())
		if err != nil {
			return "", fmt.Errorf("value: %w", err)
		}
		w.WriteString("\tconv := make([]rt.MapEntry[any, any], 0, len(v))\n\tfor gk, gv := range v {\n")
		fmt.Fprintf(&w, "\t\tk, err := b.%s(gk)\n\t\tif err != nil {\n\t\t\treturn nil, fmt.Errorf(\"key %%v: %%w\", gk, err)\n\t\t}\n", kout)
		fmt.Fprintf(&w, "\t\tx, err := b.%s(gv)\n\t\tif err != nil {\n\t\t\treturn nil, fmt.Errorf(\"value at %%v: %%w\", gk, err)\n\t\t}\n", vout)
		w.WriteString("\t\tconv = append(conv, rt.MapEntry[any, any]{Key: k, Val: x})\n\t}\n\treturn rt.MapOf(rt.Hash, rt.Equal, conv), nil\n")
	case s.Kind == SMap:
		return "", fmt.Errorf("Go %s: the adapter generator does not convert this type yet; a Map crosses as rt.Map[K, V] or a Go map", t)
	case s.Kind == SEnum:
		if err := g.outEnum(&w, s, t); err != nil {
			return "", err
		}
	case s.Kind == SHost && g.handles[TypeKey(t)] == "" && rtHeld[s.Name] != "":
		if rtHeld[s.Name] != TypeKey(t) {
			return "", fmt.Errorf("%s crosses as Go %s, not %s", s.Name, rtHeld[s.Name], t)
		}
		w.WriteString("\treturn v, nil\n")
	case s.Kind == SList && t.Kind() == reflect.Slice && !isByteKind(t.Elem()):
		elem, err := g.out(s.Elems[0], t.Elem())
		if err != nil {
			return "", fmt.Errorf("element: %w", err)
		}
		fmt.Fprintf(&w, "\tvar xs *rt.List[any]\n\tfor i := len(v) - 1; i >= 0; i-- {\n\t\tx, err := b.%s(v[i])\n\t\tif err != nil {\n\t\t\treturn nil, fmt.Errorf(\"index %%d: %%w\", i, err)\n\t\t}\n\t\txs = rt.Cons[any](x, xs)\n\t}\n\treturn xs, nil\n", elem)
	case s.Kind == SMaybe && t.Kind() == reflect.Pointer && g.handles[TypeKey(t)] == "":
		d := g.enumDesc(s)
		fmt.Fprintf(&w, "\tif v == nil {\n\t\treturn b.%s.NewVariant(1), nil\n\t}\n\tr := b.%s.NewVariant(0)\n", d, d)
		if err := g.store(&w, "r", 0, s.Elems[0], t.Elem(), "*v", false, ""); err != nil {
			return "", fmt.Errorf("Maybe payload: %w", err)
		}
		w.WriteString("\treturn r, nil\n")
	case s.Kind == SStruct && t.Kind() == reflect.Struct && g.handles[TypeKey(t)] == "":
		fields, err := goFields(t)
		if err != nil {
			return "", err
		}
		if err := sameFields(s, fields); err != nil {
			return "", err
		}
		d := g.structDesc(s)
		fmt.Fprintf(&w, "\tr := b.%s.New()\n", d)
		offsets := layoutOffsets(fieldSlots(s))
		for i, f := range s.Fields {
			if err := g.store(&w, "r", offsets[i], f.Shape, fields[f.Name].typ, "v."+fields[f.Name].path, false, fmt.Sprintf("fmt.Errorf(\"field %%q: %%w\", %q, err)", f.Name)); err != nil {
				return "", fmt.Errorf("field %s: %w", f.Name, err)
			}
		}
		w.WriteString("\treturn r, nil\n")
	case s.Kind == SDistinct && len(s.Elems) == 1 && isScalar(s.Elems[0]):
		d := g.distinctDesc(s)
		fmt.Fprintf(&w, "\tr := b.%s.New()\n", d)
		switch {
		case isTimeDuration(t):
			if s.Name != durationName {
				return "", fmt.Errorf("Go time.Duration projects to Duration, not %s", s)
			}
			w.WriteString("\tr.W[0] = rt.IntWord(int64(v))\n")
		case isTimeTime(t):
			if s.Name != instantName {
				return "", fmt.Errorf("Go time.Time projects to Instant, not %s", s)
			}
			w.WriteString("\tn, err := hostadapt.InstantNanos(v)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\tr.W[0] = rt.IntWord(n)\n")
		default:
			if err := g.store(&w, "r", 0, s.Elems[0], t, "v", false, ""); err != nil {
				return "", err
			}
		}
		w.WriteString("\treturn r, nil\n")
	case s.Kind == SHost:
		if got := g.handles[TypeKey(t)]; got != s.Name {
			return "", fmt.Errorf("Go %s is not registered as host type %s (registered: %q)", t, s.Name, got)
		}
		fmt.Fprintf(&w, "\treturn rt.HostHandle{TypeName: %q, Value: v}, nil\n", s.Name)
	default:
		return "", fmt.Errorf("no conversion from Go %s to %s", t, s)
	}
	w.WriteString("}\n\n")
	g.methods.Write(w.Bytes())
	return name, nil
}

// --- scalars -----------------------------------------------------------------

func isScalar(s *Shape) bool {
	switch s.Kind {
	case SInt, SFloat, SBool, SString, SByte, SBytes:
		return true
	}
	return false
}

// nomiGoType is the Go type an rt.Value of a scalar shape holds.
func nomiGoType(s *Shape) string {
	return map[ShapeKind]string{
		SInt: "int64", SFloat: "float64", SBool: "bool", SString: "string", SByte: "rt.Byte", SBytes: "rt.Bytes",
	}[s.Kind]
}

func fieldReader(s *Shape) string {
	return map[ShapeKind]string{
		SInt: "IntField", SFloat: "FloatField", SBool: "BoolField", SString: "StringField", SByte: "ByteField", SBytes: "BytesField",
	}[s.Kind]
}

func isByteKind(t Type) bool { return t.Kind() == reflect.Uint8 }

// compatible is the marshaller's projection table for scalars.
func compatible(s *Shape, t Type) error {
	if isTimeDuration(t) || isTimeTime(t) {
		return fmt.Errorf("Go %s projects to %s, not %s", t, map[bool]string{true: "Duration", false: "Instant"}[isTimeDuration(t)], s)
	}
	ok := false
	switch s.Kind {
	case SInt:
		switch t.Kind() {
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
			ok = true
		}
	case SFloat:
		ok = t.Kind() == reflect.Float32 || t.Kind() == reflect.Float64
	case SBool:
		ok = t.Kind() == reflect.Bool
	case SString:
		ok = t.Kind() == reflect.String
	case SByte:
		ok = t.Kind() == reflect.Uint8
	case SBytes:
		ok = isRtBytes(t) || (t.Kind() == reflect.Slice && isByteKind(t.Elem()))
	}
	if !ok {
		return fmt.Errorf("Go %s does not project to %s", t, s)
	}
	return nil
}

// narrow converts x, a Nomi scalar's Go value, to Go type t. A fallible
// conversion is an expression of two values, (T, error).
func (g *Generator) narrow(s *Shape, t Type, x string) (string, bool, error) {
	goT, err := g.typ(t)
	if err != nil {
		return "", false, err
	}
	switch s.Kind {
	case SInt:
		switch t.Kind() {
		case reflect.Int64:
			return fmt.Sprintf("%s(%s)", goT, x), false, nil
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32:
			return fmt.Sprintf("hostadapt.ToSigned[%s](%s, %q)", goT, x, t.String()), true, nil
		default:
			return fmt.Sprintf("hostadapt.ToUnsigned[%s](%s, %q)", goT, x, t.String()), true, nil
		}
	case SFloat:
		if t.Kind() == reflect.Float32 {
			return fmt.Sprintf("hostadapt.ToFloat32[%s](%s, %q)", goT, x, t.String()), true, nil
		}
		return fmt.Sprintf("%s(%s)", goT, x), false, nil
	case SBool, SString, SByte:
		return fmt.Sprintf("%s(%s)", goT, x), false, nil
	case SBytes:
		if isRtBytes(t) || isPredeclared(t.Elem(), "byte") {
			return fmt.Sprintf("%s(%s)", goT, x), false, nil
		}
		elemT, err := g.typ(t.Elem())
		if err != nil {
			return "", false, err
		}
		return fmt.Sprintf("func() %s { out := make(%s, len(%s)); for i := range len(%s) { out[i] = %s(%s[i]) }; return out }()", goT, goT, x, x, elemT, x), false, nil
	}
	return "", false, fmt.Errorf("%s is not a scalar", s)
}

// widen converts x, a Go value of type t, to the Go value an rt.Value of
// scalar shape s holds.
func (g *Generator) widen(s *Shape, t Type, x string) (string, bool, error) {
	if err := compatible(s, t); err != nil {
		return "", false, err
	}
	switch s.Kind {
	case SInt:
		switch t.Kind() {
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
			return fmt.Sprintf("int64(%s)", x), false, nil
		}
		return fmt.Sprintf("hostadapt.FromUnsigned(%s, %q)", x, t.String()), true, nil
	case SFloat:
		return fmt.Sprintf("float64(%s)", x), false, nil
	case SBool:
		return fmt.Sprintf("bool(%s)", x), false, nil
	case SString:
		return fmt.Sprintf("string(%s)", x), false, nil
	case SByte:
		return fmt.Sprintf("rt.Byte(%s)", x), false, nil
	case SBytes:
		if isRtBytes(t) || isPredeclared(t.Elem(), "byte") {
			return fmt.Sprintf("rt.Bytes(%s)", x), false, nil
		}
		return fmt.Sprintf("func() rt.Bytes { out := make([]byte, len(%s)); for i := range len(%s) { out[i] = byte(%s[i]) }; return rt.Bytes(out) }()", x, x, x), false, nil
	}
	return "", false, fmt.Errorf("%s is not a scalar", s)
}

// --- descriptors -------------------------------------------------------------

func (g *Generator) addDesc(key, spec, tuple string) string {
	if f, ok := g.descMemo[key]; ok {
		return f
	}
	f := fmt.Sprintf("d%d", len(g.descs))
	g.descMemo[key] = f
	g.descs = append(g.descs, descField{field: f, spec: spec, tuple: tuple})
	return f
}

func (g *Generator) structDesc(s *Shape) string {
	var b strings.Builder
	fmt.Fprintf(&b, "&hostadapt.DescSpec{Name: %q, Kind: rt.KindStruct, Fields: []rt.FieldSpec{", s.Name)
	for _, f := range s.Fields {
		fmt.Fprintf(&b, "{Name: %q, Type: %s}, ", f.Name, slotExpr(f.Shape.Slot()))
	}
	b.WriteString("}}")
	return g.addDesc("struct|"+shapeKey(s), b.String(), "")
}

func (g *Generator) distinctDesc(s *Shape) string {
	inner := "nil"
	if len(s.Elems) == 1 {
		inner = fmt.Sprintf("hostadapt.Slot(%s)", slotExpr(s.Elems[0].Slot()))
	}
	spec := fmt.Sprintf("&hostadapt.DescSpec{Name: %q, Kind: rt.KindDistinct, Inner: %s}", s.Name, inner)
	return g.addDesc("distinct|"+shapeKey(s), spec, "")
}

// enumDesc is the descriptor of a Maybe or Result instantiation. Tags follow
// the declarations: `Some` 0 and `None` 1, `Ok` 0 and `Err` 1.
func (g *Generator) enumDesc(s *Shape) string {
	var spec string
	switch s.Kind {
	case SMaybe:
		spec = fmt.Sprintf("&hostadapt.DescSpec{Name: %q, Kind: rt.KindEnum, Variants: []rt.VariantSpec{"+
			"{Name: \"Some\", Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: %s}}}, "+
			"{Name: \"None\", Shape: rt.VariantBare}}}", maybeName, slotExpr(s.Elems[0].Slot()))
	case SResult:
		spec = fmt.Sprintf("&hostadapt.DescSpec{Name: %q, Kind: rt.KindEnum, Variants: []rt.VariantSpec{"+
			"{Name: \"Ok\", Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: %s}}}, "+
			"{Name: \"Err\", Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: %s}}}}}",
			resultName, slotExpr(s.Elems[0].Slot()), slotExpr(s.Elems[1].Slot()))
	case SEnum:
		var b strings.Builder
		fmt.Fprintf(&b, "&hostadapt.DescSpec{Name: %q, Kind: rt.KindEnum, Variants: []rt.VariantSpec{", s.Name)
		for _, v := range s.Variants {
			switch {
			case v.Shape == rt.VariantBare:
				fmt.Fprintf(&b, "{Name: %q, Shape: rt.VariantBare}, ", v.Name)
			case v.Err != nil:
				// An unresolvable positional payload is still one payload,
				// held by reference.
				fmt.Fprintf(&b, "{Name: %q, Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: rt.SlotRef}}}, ", v.Name)
			default:
				shape := "rt.VariantPositional"
				if v.Shape == rt.VariantFields {
					shape = "rt.VariantFields"
				}
				fmt.Fprintf(&b, "{Name: %q, Shape: %s, Fields: []rt.FieldSpec{", v.Name, shape)
				for _, f := range v.Fields {
					if f.Name == "" {
						fmt.Fprintf(&b, "{Type: %s}, ", slotExpr(f.Shape.Slot()))
					} else {
						fmt.Fprintf(&b, "{Name: %q, Type: %s}, ", f.Name, slotExpr(f.Shape.Slot()))
					}
				}
				b.WriteString("}}, ")
			}
		}
		b.WriteString("}}")
		spec = b.String()
	default:
		panic("hostgen: enumDesc of " + s.String())
	}
	return g.addDesc("enum|"+spec, spec, "")
}

func (g *Generator) tupleDesc(slots []rt.SlotType) string {
	parts := make([]string, len(slots))
	for i, s := range slots {
		parts[i] = slotExpr(s)
	}
	expr := "rt.TupleDesc(" + strings.Join(parts, ", ") + ")"
	return g.addDesc("tuple|"+expr, "", expr)
}

func slotExpr(s rt.SlotType) string {
	return map[rt.SlotType]string{
		rt.SlotRef: "rt.SlotRef", rt.SlotInt: "rt.SlotInt", rt.SlotFloat: "rt.SlotFloat", rt.SlotBool: "rt.SlotBool",
		rt.SlotByte: "rt.SlotByte", rt.SlotString: "rt.SlotString", rt.SlotBytes: "rt.SlotBytes",
	}[s]
}

func fieldSlots(s *Shape) []rt.SlotType {
	out := make([]rt.SlotType, len(s.Fields))
	for i, f := range s.Fields {
		out[i] = f.Shape.Slot()
	}
	return out
}

// layoutOffsets is rt's layout rule: each field's offset within its bank, in
// field order.
func layoutOffsets(slots []rt.SlotType) []int {
	var nw, ns, nr int
	out := make([]int, len(slots))
	for i, s := range slots {
		switch s.Bank() {
		case rt.BankWord:
			out[i] = nw
			nw++
		case rt.BankStr:
			out[i] = ns
			ns++
		default:
			out[i] = nr
			nr++
		}
	}
	return out
}

func shapeKey(s *Shape) string {
	switch s.Kind {
	case SStruct, SDistinct, SHost, SEnum:
		return fmt.Sprintf("%d:%s", s.Kind, s.Name)
	}
	parts := make([]string, len(s.Elems))
	for i, e := range s.Elems {
		parts[i] = shapeKey(e)
	}
	k := fmt.Sprintf("%d(%s)", s.Kind, strings.Join(parts, ","))
	if s.Ret != nil {
		k += "->" + shapeKey(s.Ret)
	}
	return k
}

// --- Go types ----------------------------------------------------------------

type goField struct {
	path string // selector path from the struct value, `A.B`
	typ  Type
}

// goFields is the marshaller's field walk: exported fields, embedded structs
// flattened, `nomi:"name"` and `nomi:"-"` tags, snake_case otherwise.
func goFields(t Type) (map[string]goField, error) {
	out := map[string]goField{}
	var walk func(t Type, prefix string) error
	walk = func(t Type, prefix string) error {
		for i := range t.NumField() {
			f := t.Field(i)
			if !f.Exported {
				continue
			}
			if f.Anonymous && f.Type.Kind() == reflect.Struct {
				if err := walk(f.Type, prefix+f.Name+"."); err != nil {
					return err
				}
				continue
			}
			tag := f.Tag.Get("nomi")
			if tag == "-" {
				continue
			}
			name := tag
			if name == "" {
				name = strcase.ToSnake(f.Name)
			}
			if _, dup := out[name]; dup {
				return fmt.Errorf("embedded struct field %q collides with outer field", name)
			}
			out[name] = goField{path: prefix + f.Name, typ: f.Type}
		}
		return nil
	}
	return out, walk(t, "")
}

// sameFields requires the Go struct to carry exactly the declared fields. The
// marshaller builds a record from whatever the Go struct has; a generated
// adapter writes the declared layout, so a drift between the two is refused
// here, at generation, rather than producing a record the declaration does not
// describe.
func sameFields(s *Shape, fields map[string]goField) error {
	declared := map[string]bool{}
	for _, f := range s.Fields {
		declared[f.Name] = true
		if _, ok := fields[f.Name]; !ok {
			return fmt.Errorf("%s declares field %s and the Go struct has no field projecting to it", s.Name, f.Name)
		}
	}
	for name := range fields {
		if !declared[name] {
			return fmt.Errorf("the Go struct has field %s and %s declares none", name, s.Name)
		}
	}
	return nil
}

// typ spells a Go type in the generated file, importing its package.
func (g *Generator) typ(t Type) (string, error) {
	if base, args, ok := rtGenericArgs(t); ok {
		spelled := make([]string, len(args))
		for i, a := range args {
			s, err := g.typ(a)
			if err != nil {
				return "", err
			}
			spelled[i] = s
		}
		return "rt." + base + "[" + strings.Join(spelled, ", ") + "]", nil
	}
	if t.Name() != "" {
		if strings.ContainsAny(t.Name(), "[]") {
			return "", fmt.Errorf("Go %s is a generic instantiation; the generator does not spell those", t)
		}
		if t.PkgPath() == "" || (g.ownPkg != "" && t.PkgPath() == g.ownPkg) {
			return t.Name(), nil
		}
		return g.alias(t.PkgPath()) + "." + t.Name(), nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		e, err := g.typ(t.Elem())
		return "*" + e, err
	case reflect.Slice:
		e, err := g.typ(t.Elem())
		return "[]" + e, err
	case reflect.Map:
		k, err := g.typ(t.Key())
		if err != nil {
			return "", err
		}
		v, err := g.typ(t.Elem())
		return "map[" + k + "]" + v, err
	case reflect.Func:
		in := make([]string, t.NumIn())
		for i := range t.NumIn() {
			s, err := g.typ(t.In(i))
			if err != nil {
				return "", err
			}
			in[i] = s
		}
		out := make([]string, t.NumOut())
		for i := range t.NumOut() {
			s, err := g.typ(t.Out(i))
			if err != nil {
				return "", err
			}
			out[i] = s
		}
		sig := "func(" + strings.Join(in, ", ") + ")"
		switch len(out) {
		case 0:
		case 1:
			sig += " " + out[0]
		default:
			sig += " (" + strings.Join(out, ", ") + ")"
		}
		return sig, nil
	}
	return "", fmt.Errorf("Go %s has no spelling the generator writes", t)
}

func (g *Generator) alias(pkgPath string) string {
	if a, ok := g.imports[pkgPath]; ok {
		return a
	}
	base := path.Base(pkgPath)
	a := base
	for i := 2; g.taken[a]; i++ {
		a = fmt.Sprintf("%s%d", base, i)
	}
	g.taken[a] = true
	g.imports[pkgPath] = a
	return a
}

// funcName spells the Go function a binding holds, read off the linked
// symbol so the generated call cannot disagree with the table.
func (g *Generator) funcName(fv reflect.Value) (string, error) {
	f := runtime.FuncForPC(fv.Pointer())
	if f == nil {
		return "", fmt.Errorf("the function value has no symbol")
	}
	full := f.Name() // nomi/stdregex.FFICompile
	slash := strings.LastIndex(full, "/")
	dot := strings.Index(full[slash+1:], ".")
	if dot < 0 {
		return "", fmt.Errorf("symbol %q has no package qualifier", full)
	}
	pkg, sym := full[:slash+1+dot], full[slash+1+dot+1:]
	if strings.ContainsAny(sym, ".[]") || strings.HasPrefix(sym, "func") {
		return "", fmt.Errorf("symbol %q is not a top-level function; a closure or method value cannot be called by name", full)
	}
	return g.alias(pkg) + "." + sym, nil
}

func (g *Generator) fresh(prefix string) string {
	g.next++
	return fmt.Sprintf("%s%d", prefix, g.next)
}

// paramList renders a declaration's parameters for the adapter's comment.
func paramList(d *ast.ExternFunc) string {
	parts := make([]string, len(d.Params))
	for i, p := range d.Params {
		t := "?"
		if p.TypeAnnotation != nil {
			t = p.TypeAnnotation.TypeString()
		}
		parts[i] = p.Name + ": " + t
	}
	return strings.Join(parts, ", ")
}

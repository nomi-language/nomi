// rtHeldRefusal refuses an rt-held host type against Go t, which is not the
// Go type its value is.
func rtHeldRefusal(s *Shape, t reflect.Type) error {
	return fmt.Errorf("%s crosses as Go %s, not %s", s.Name, rtHeld[s.Name], t)
}

func isScalar(s *Shape) bool {
	switch s.Kind {
	case SInt, SFloat, SBool, SString, SByte, SBytes:
		return true
	}
	return false
}

// nomiGoType is the Go type an rt.Value of a scalar shape holds.
func nomiGoType(s *Shape) string {
	return map[ShapeKind]string{
		SInt: "int64", SFloat: "float64", SBool: "bool", SString: "string", SByte: "rt.Byte", SBytes: "rt.Bytes",
	}[s.Kind]
}

func fieldReader(s *Shape) string {
	return map[ShapeKind]string{
		SInt: "IntValueField", SFloat: "FloatField", SBool: "BoolField", SString: "StringField", SByte: "ByteField", SBytes: "BytesField",
	}[s.Kind]
}

// isRtInt reports whether t is rt.Int, an Int of any size.
func isRtInt(t reflect.Type) bool { return isNamed(t, rtPkg, "Int") }

// isRtDuration reports whether t is rt.Duration, the Go type std's
// Duration crosses as.
func isRtDuration(t reflect.Type) bool { return isNamed(t, rtPkg, "Duration") }

// isRtInstant reports whether t is rt.Instant, the Go type std's Instant
// crosses as.
func isRtInstant(t reflect.Type) bool { return isNamed(t, rtPkg, "Instant") }

func isByteKind(t reflect.Type) bool { return t.Kind() == reflect.Uint8 }

// isByteSlice reports whether t is a Go slice of the predeclared byte.
func isByteSlice(t reflect.Type) bool {
	return t.Kind() == reflect.Slice && t.Elem() == reflect.TypeFor[byte]()
}

// isSigned reports whether t is a Go signed integer.
func isSigned(t reflect.Type) bool {
	switch t.Kind() {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return true
	}
	return false
}

// compatible is the projection table for scalars: an Int is rt.Int or a Go
// integer of a fixed width (fits), a Float a float64, a Bool a bool, a
// String a string, a Byte a uint8, and Bytes rt.Bytes or a byte slice.
func compatible(s *Shape, t reflect.Type) error {
	ok := false
	switch s.Kind {
	case SInt:
		switch t.Kind() {
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
			ok = true
		}
		ok = ok || isRtInt(t)
	case SFloat:
		ok = t.Kind() == reflect.Float64
	case SBool:
		ok = t.Kind() == reflect.Bool
	case SString:
		ok = t.Kind() == reflect.String
	case SByte:
		ok = t.Kind() == reflect.Uint8
	case SBytes:
		ok = isRtBytes(t) || isByteSlice(t)
	}
	if !ok {
		return fmt.Errorf("Go %s does not project to %s", t, s)
	}
	return nil
}

// narrow converts x, a Nomi scalar's Go value, to Go type t. A fallible
// conversion is an expression of two values, (T, error).
func (g *Generator) narrow(s *Shape, t reflect.Type, x string) (string, bool, error) {
	goT, err := g.typ(t)
	if err != nil {
		return "", false, err
	}
	switch s.Kind {
	case SInt:
		// x is an Int value: an int64, or a *rt.BigInt past its range.
		if isRtInt(t) {
			return fmt.Sprintf("rt.IntOf(%s)", x), false, nil
		}
		if err := g.fits(s, t); err != nil {
			return "", false, err
		}
		if isSigned(t) {
			return fmt.Sprintf("hostadapt.ToSigned[%s](%s, %q)", goT, x, t.String()), true, nil
		}
		return fmt.Sprintf("hostadapt.ToUnsigned[%s](%s, %q)", goT, x, t.String()), true, nil
	case SFloat, SBool, SString, SByte, SBytes:
		return fmt.Sprintf("%s(%s)", goT, x), false, nil
	}
	return "", false, fmt.Errorf("%s is not a scalar", s)
}

// widen converts x, a Go value of type t, to the Go value an rt.Value of
// scalar shape s holds.
func (g *Generator) widen(s *Shape, t reflect.Type, x string) (string, error) {
	if err := compatible(s, t); err != nil {
		return "", err
	}
	switch s.Kind {
	case SInt:
		switch {
		case isRtInt(t):
			return fmt.Sprintf("%s.Value()", x), nil
		case isSigned(t):
			return fmt.Sprintf("rt.Value(int64(%s))", x), nil
		}
		return fmt.Sprintf("rt.IntFromUint64(uint64(%s))", x), nil
	case SFloat:
		return fmt.Sprintf("float64(%s)", x), nil
	case SBool:
		return fmt.Sprintf("bool(%s)", x), nil
	case SString:
		return fmt.Sprintf("string(%s)", x), nil
	case SByte:
		return fmt.Sprintf("rt.Byte(%s)", x), nil
	case SBytes:
		return fmt.Sprintf("rt.Bytes(%s)", x), nil
	}
	return "", fmt.Errorf("%s is not a scalar", s)
}

// --- descriptors -------------------------------------------------------------

func (g *Generator) addDesc(key, spec, tuple string) string {
	if f, ok := g.descMemo[key]; ok {
		return f
	}
	f := fmt.Sprintf("d%d", len(g.descs))
	g.descMemo[key] = f
	g.descs = append(g.descs, descField{field: f, spec: spec, tuple: tuple})
	return f
}

func (g *Generator) structDesc(s *Shape) string {
	var b strings.Builder
	fmt.Fprintf(&b, "&hostadapt.DescSpec{Name: %q, Kind: rt.KindStruct, Fields: []rt.FieldSpec{", s.Name)
	for _, f := range s.Fields {
		fmt.Fprintf(&b, "{Name: %q, Type: %s}, ", f.Name, slotExpr(f.Shape.Slot()))
	}
	b.WriteString("}}")
	// Keyed by the spec, not by shapeKey's name: two modules may each
	// declare a describe.Table, of different fields, and each must get its
	// own descriptor.
	return g.addDesc("struct|"+b.String(), b.String(), "")
}

// distinctDesc is the descriptor of a distinct type over a scalar.
func (g *Generator) distinctDesc(s *Shape) string {
	spec := fmt.Sprintf("&hostadapt.DescSpec{Name: %q, Kind: rt.KindDistinct, Inner: hostadapt.Slot(%s)}", s.Name, slotExpr(s.Elems[0].Slot()))
	return g.addDesc("distinct|"+spec, spec, "")
}

// enumDesc is the descriptor of an Option or Result instantiation. Tags follow
// the declarations: `Some` 0 and `None` 1, `Ok` 0 and `Err` 1.
func (g *Generator) enumDesc(s *Shape) string {
	var spec string
	switch s.Kind {
	case SOption:
		spec = fmt.Sprintf("&hostadapt.DescSpec{Name: %q, Kind: rt.KindEnum, Variants: []rt.VariantSpec{"+
			"{Name: \"Some\", Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: %s}}}, "+
			"{Name: \"None\", Shape: rt.VariantBare}}}", optionName, slotExpr(s.Elems[0].Slot()))
	case SResult:
		spec = fmt.Sprintf("&hostadapt.DescSpec{Name: %q, Kind: rt.KindEnum, Variants: []rt.VariantSpec{"+
			"{Name: \"Ok\", Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: %s}}}, "+
			"{Name: \"Err\", Shape: rt.VariantPositional, Fields: []rt.FieldSpec{{Type: %s}}}}}",
			resultName, slotExpr(s.Elems[0].Slot()), slotExpr(s.Elems[1].Slot()))
	case SEnum:
		var b strings.Builder
		fmt.Fprintf(&b, "&hostadapt.DescSpec{Name: %q, Kind: rt.KindEnum, Variants: []rt.VariantSpec{", s.Name)
		for _, v := range s.Variants {
			switch {
			case v.Shape == rt.VariantBare:
				fmt.Fprintf(&b, "{Name: %q, Shape: rt.VariantBare}, ", v.Name)
			default:
				shape := "rt.VariantPositional"
				if v.Shape == rt.VariantFields {
					shape = "rt.VariantFields"
				}
				fmt.Fprintf(&b, "{Name: %q, Shape: %s, Fields: []rt.FieldSpec{", v.Name, shape)
				for _, f := range v.Fields {
					if f.Name == "" {
						fmt.Fprintf(&b, "{Type: %s}, ", slotExpr(f.Shape.Slot()))
					} else {
						fmt.Fprintf(&b, "{Name: %q, Type: %s}, ", f.Name, slotExpr(f.Shape.Slot()))
					}
				}
				b.WriteString("}}, ")
			}
		}
		b.WriteString("}}")
		spec = b.String()
	default:
		panic("hostgen: enumDesc of " + s.String())
	}
	return g.addDesc("enum|"+spec, spec, "")
}

func (g *Generator) tupleDesc(slots []rt.SlotType) string {
	parts := make([]string, len(slots))
	for i, s := range slots {
		parts[i] = slotExpr(s)
	}
	expr := "rt.TupleDesc(" + strings.Join(parts, ", ") + ")"
	return g.addDesc("tuple|"+expr, "", expr)
}

func slotExpr(s rt.SlotType) string {
	return map[rt.SlotType]string{
		rt.SlotRef: "rt.SlotRef", rt.SlotInt: "rt.SlotInt", rt.SlotFloat: "rt.SlotFloat", rt.SlotBool: "rt.SlotBool",
		rt.SlotByte: "rt.SlotByte", rt.SlotString: "rt.SlotString", rt.SlotBytes: "rt.SlotBytes",
	}[s]
}

func fieldSlots(s *Shape) []rt.SlotType {
	out := make([]rt.SlotType, len(s.Fields))
	for i, f := range s.Fields {
		out[i] = f.Shape.Slot()
	}
	return out
}

// layoutOffsets is rt's layout rule: each field's offset within its bank, in
// field order.
func layoutOffsets(slots []rt.SlotType) []int {
	var nw, ns, nr int
	out := make([]int, len(slots))
	for i, s := range slots {
		switch s.Bank() {
		case rt.BankWord:
			out[i] = nw
			nw++
		case rt.BankStr:
			out[i] = ns
			ns++
		default:
			out[i] = nr
			nr++
		}
	}
	return out
}

func shapeKey(s *Shape) string { return shapeKeyOf(s, false) }

// inShapeKey is shapeKey with each nested Int's declared range, which
// decides whether it reads into a fixed-width Go integer (fits), so a
// conversion checked for one range is never reused for another.
func inShapeKey(s *Shape) string { return shapeKeyOf(s, true) }

func shapeKeyOf(s *Shape, ranges bool) string {
	switch s.Kind {
	case SStruct, SDistinct, SHost, SEnum:
		return fmt.Sprintf("%d:%s", s.Kind, s.Name)
	}
	parts := make([]string, len(s.Elems))
	for i, e := range s.Elems {
		parts[i] = shapeKeyOf(e, ranges)
	}
	k := fmt.Sprintf("%d(%s)", s.Kind, strings.Join(parts, ","))
	if ranges && s.Kind == SInt {
		k += s.Range.key()
	}
	if s.Ret != nil {
		k += "->" + shapeKeyOf(s.Ret, ranges)
	}
	return k
}

// --- Go types ----------------------------------------------------------------

type goField struct {
	path string // the Go field's name, the selector from the struct value
	typ  reflect.Type
}

// goFields is a Go struct's fields by the Nomi field name each projects to,
// its Go name in snake_case. Every field is exported, since a generated
// adapter in another package reads and writes them all.
func goFields(t reflect.Type) (map[string]goField, error) {
	out := map[string]goField{}
	for i := range t.NumField() {
		f := t.Field(i)
		if !f.IsExported() {
			return nil, fmt.Errorf("Go %s has unexported field %s, which an adapter cannot reach", t, f.Name)
		}
		name := strcase.ToSnake(f.Name)
		if _, dup := out[name]; dup {
			return nil, fmt.Errorf("Go %s has two fields named %s in snake_case", t, name)
		}
		out[name] = goField{path: f.Name, typ: f.Type}
	}
	return out, nil
}

// sameFields requires the Go struct to carry exactly the declared fields. The
// marshaller builds a record from whatever the Go struct has; a generated
// adapter writes the declared layout, so a drift between the two is refused
// here, at generation, rather than producing a record the declaration does not
// describe.
func sameFields(s *Shape, fields map[string]goField) error {
	declared := map[string]bool{}
	for _, f := range s.Fields {
		declared[f.Name] = true
		if _, ok := fields[f.Name]; !ok {
			return fmt.Errorf("%s declares field %s and the Go struct has no field projecting to it", s.Name, f.Name)
		}
	}
	for name := range fields {
		if !declared[name] {
			return fmt.Errorf("the Go struct has field %s and %s declares none", name, s.Name)
		}
	}
	return nil
}

// tupleStruct reports whether Go type t is how a binding answers tuple shape
// s: an anonymous struct whose fields are F0, F1, ... in order, one per
// component, which is how internal/irbuild reads an rt signature's tuple too
// (tupleKindOfGoType). Several Go results are a tuple too (results).
func (g *Generator) tupleStruct(s *Shape, t reflect.Type) bool {
	if s.Kind != STuple || t.Kind() != reflect.Struct || t.Name() != "" || t.NumField() != len(s.Elems) {
		return false
	}
	for i := range t.NumField() {
		if t.Field(i).Name != fmt.Sprintf("F%d", i) {
			return false
		}
	}
	return true
}

// typ spells a Go type in the generated file, importing its package.
func (g *Generator) typ(t reflect.Type) (string, error) {
	if base, args, ok := rtGenericArgs(t); ok {
		spelled := make([]string, len(args))
		for i, a := range args {
			s, err := g.typ(a)
			if err != nil {
				return "", err
			}
			spelled[i] = s
		}
		return "rt." + base + "[" + strings.Join(spelled, ", ") + "]", nil
	}
	if t.Name() != "" {
		if strings.ContainsAny(t.Name(), "[]") {
			return "", fmt.Errorf("Go %s is a generic instantiation; the generator does not spell those", t)
		}
		if t.PkgPath() == "" {
			return t.Name(), nil
		}
		return g.alias(t.PkgPath()) + "." + t.Name(), nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		e, err := g.typ(t.Elem())
		return "*" + e, err
	case reflect.Slice:
		e, err := g.typ(t.Elem())
		return "[]" + e, err
	case reflect.Func:
		// A callback, which answers one value (callback).
		if t.NumOut() != 1 {
			break
		}
		in := make([]string, t.NumIn())
		for i := range t.NumIn() {
			s, err := g.typ(t.In(i))
			if err != nil {
				return "", err
			}
			in[i] = s
		}
		out, err := g.typ(t.Out(0))
		if err != nil {
			return "", err
		}
		return "func(" + strings.Join(in, ", ") + ") " + out, nil
	case reflect.Struct:
		// An anonymous struct: a binding's tuple (tupleStruct).
		fields := make([]string, t.NumField())
		for i := range t.NumField() {
			f := t.Field(i)
			s, err := g.typ(f.Type)
			if err != nil {
				return "", err
			}
			fields[i] = f.Name + " " + s
		}
		return "struct{ " + strings.Join(fields, "; ") + " }", nil
	}
	return "", fmt.Errorf("Go %s has no spelling the generator writes", t)
}

func (g *Generator) alias(pkgPath string) string {
	if a, ok := g.imports[pkgPath]; ok {
		return a
	}
	base := path.Base(pkgPath)
	a := base
	for i := 2; g.taken[a]; i++ {
		a = fmt.Sprintf("%s%d", base, i)
	}
	g.taken[a] = true
	g.imports[pkgPath] = a
	return a
}

// funcName spells the Go function a binding holds, read off the linked
// symbol so the generated call cannot disagree with the table.
func (g *Generator) funcName(fv reflect.Value) (string, error) {
	f := runtime.FuncForPC(fv.Pointer())
	if f == nil {
		return "", fmt.Errorf("the function value has no symbol")
	}
	full := f.Name() // nomi/stdregex.HostCompile
	slash := strings.LastIndex(full, "/")
	dot := strings.Index(full[slash+1:], ".")
	if dot < 0 {
		return "", fmt.Errorf("symbol %q has no package qualifier", full)
	}
	pkg, sym := full[:slash+1+dot], full[slash+1+dot+1:]
	if strings.ContainsAny(sym, ".[]") || strings.HasPrefix(sym, "func") {
		return "", fmt.Errorf("symbol %q is not a top-level function; a closure or method value cannot be called by name", full)
	}
	return g.alias(pkg) + "." + sym, nil
}

func (g *Generator) fresh(prefix string) string {
	g.next++
	return fmt.Sprintf("%s%d", prefix, g.next)
}

// paramList renders a declaration's parameters for the adapter's comment.
func paramList(d *ast.ExternFunc) string {
	parts := make([]string, len(d.Params))
	for i, p := range d.Params {
		t := "?"
		if p.TypeAnnotation != nil {
			t = p.TypeAnnotation.TypeString()
		}
		parts[i] = p.Name + ": " + t
	}
	return strings.Join(parts, ", ")
}

// Command pingen writes internal/gotoolchain/pinned_gen.go: the SHA-256 of
// go.dev's archive of a Go release for each host `nomi` is released for, which
// the managed toolchain checks a download against.
//
//	go run ./internal/gotoolchain/pingen [version...]    (from the repository root)
//	go run ./internal/gotoolchain/pingen -check [version]
//
// With no version it pins the Go that runs it (the one a release is built
// with) and keeps every version already pinned. The checksums come from
// go.dev's release list (https://go.dev/dl/?mode=json&include=all), the same
// values go.dev's download page shows. -check writes nothing and fails when
// the version (by default the running Go) is not pinned for every host;
// scripts/release.sh runs it, since a release whose Go is not pinned could
// not download its own toolchain.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"runtime"
	"sort"
	"strings"
	"time"

	"github.com/nomi-language/nomi/internal/gotoolchain"
)

// hosts are the platforms scripts/release.sh ships `nomi` for.
var hosts = []struct{ goos, goarch string }{
	{"darwin", "arm64"},
	{"darwin", "amd64"},
	{"linux", "amd64"},
	{"linux", "arm64"},
	{"windows", "amd64"},
}

func main() {
	check := flag.Bool("check", false, "fail unless the version is pinned for every host; write nothing")
	out := flag.String("o", "internal/gotoolchain/pinned_gen.go", "the file to write")
	flag.Parse()
	versions := flag.Args()
	if len(versions) == 0 {
		versions = []string{runtime.Version()}
	}
	if *check {
		pinned := gotoolchain.PinnedArchives()
		var missing []string
		for _, v := range versions {
			for _, h := range hosts {
				if name := gotoolchain.ArchiveName(v, h.goos, h.goarch); pinned[name] == "" {
					missing = append(missing, name)
				}
			}
		}
		if len(missing) > 0 {
			fmt.Fprintf(os.Stderr, "pingen: no checksum is pinned for %s; run `go run ./internal/gotoolchain/pingen %s` and commit internal/gotoolchain/pinned_gen.go\n",
				strings.Join(missing, ", "), strings.Join(versions, " "))
			os.Exit(1)
		}
		return
	}
	pins := gotoolchain.PinnedArchives()
	releases, err := releaseList()
	if err != nil {
		fmt.Fprintln(os.Stderr, "pingen:", err)
		os.Exit(1)
	}
	for _, v := range versions {
		files, ok := releases[v]
		if !ok {
			fmt.Fprintf(os.Stderr, "pingen: go.dev lists no release %s\n", v)
			os.Exit(1)
		}
		for _, h := range hosts {
			name := gotoolchain.ArchiveName(v, h.goos, h.goarch)
			sum, ok := files[name]
			if !ok {
				fmt.Fprintf(os.Stderr, "pingen: go.dev lists no archive %s\n", name)
				os.Exit(1)
			}
			pins[name] = sum
		}
	}
	names := make([]string, 0, len(pins))
	for name := range pins {
		names = append(names, name)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gotoolchain/pingen from go.dev's release list. DO NOT EDIT.\n\n")
	b.WriteString("package gotoolchain\n\n")
	b.WriteString("// pinned is the SHA-256 of each Go archive the managed toolchain may install.\n")
	b.WriteString("var pinned = map[string]string{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", name, pins[name])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "pingen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "pingen:", err)
		os.Exit(1)
	}
}

// releaseList is go.dev's release list: each version's archive checksums by
// file name.
func releaseList() (map[string]map[string]string, error) {
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get("https://go.dev/dl/?mode=json&include=all")
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("go.dev/dl: %s", resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	var list []struct {
		Version string
		Files   []struct {
			Filename string
			Kind     string
			SHA256   string `json:"sha256"`
		}
	}
	if err := json.Unmarshal(data, &list); err != nil {
		return nil, err
	}
	out := map[string]map[string]string{}
	for _, r := range list {
		files := map[string]string{}
		for _, f := range r.Files {
			if f.Kind == "archive" {
				files[f.Filename] = f.SHA256
			}
		}
		out[r.Version] = files
	}
	return out, nil
}

//go:build ignore

// langnames_gen writes langnames.go: the English name of the language of
// every locale the compiled-in CLDR data has, from x/text's display names.
// The checker names a locale's language in its message diagnostics ("2, 3
// and 4 select `few` in Polish"); a table of these names alone keeps
// x/text/language/display, about 2.4 MB of WebAssembly, out of the binaries.
//
//	go generate ./internal/catalogcheck
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"golang.org/x/text/language"
	"golang.org/x/text/language/display"

	"github.com/nomi-language/nomi/internal/cldrfull"
)

func main() {
	names := map[string]string{}
	for _, tag := range cldrfull.Full().Locales() {
		t, err := language.Parse(tag)
		if err != nil {
			continue
		}
		base, _ := t.Base()
		if name := display.English.Languages().Name(base); name != "" && base.String() != "und" {
			names[base.String()] = name
		}
	}
	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("// Code generated by langnames_gen.go; DO NOT EDIT.\n\npackage catalogcheck\n\n")
	b.WriteString("// languageNames is the English name of each language CLDR's locales are\n// in, by its base tag.\n")
	b.WriteString("var languageNames = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, names[k])
	}
	b.WriteString("}\n")
	if err := os.WriteFile("langnames.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}

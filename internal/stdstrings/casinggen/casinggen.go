// Package casinggen writes internal/stdstrings/casing_tables.go from the
// Unicode 17 SpecialCasing.txt and CaseFolding.txt vendored in
// internal/stdstrings/data: the full case mappings and the full case
// folding where they differ from the simple mappings Go's unicode package
// (Unicode 17 since Go 1.27) gives. The language-specific mappings
// (Turkish, Azeri, Lithuanian) and Final_Sigma are rules in casing.go;
// generation fails if SpecialCasing.txt holds a conditional mapping
// casing.go does not implement. `go generate ./internal/stdstrings` runs
// ./gen; TestTablesAreCurrent fails while the tables are stale.
package casinggen

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

// conditional is every conditional line of SpecialCasing.txt casing.go
// implements, as `code; condition`.
var conditional = map[string]bool{
	"03A3; Final_Sigma":          true,
	"0307; lt After_Soft_Dotted": true,
	"0049; lt More_Above":        true,
	"004A; lt More_Above":        true,
	"012E; lt More_Above":        true,
	"00CC; lt":                   true,
	"00CD; lt":                   true,
	"0128; lt":                   true,
	"0130; tr":                   true,
	"0130; az":                   true,
	"0307; tr After_I":           true,
	"0307; az After_I":           true,
	"0049; tr Not_Before_Dot":    true,
	"0049; az Not_Before_Dot":    true,
	"0069; tr":                   true,
	"0069; az":                   true,
}

func fields(path string, each func(f []string, line string) error) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.Index(line, "#"); i >= 0 {
			line = line[:i]
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		fs := strings.Split(line, ";")
		for i := range fs {
			fs[i] = strings.TrimSpace(fs[i])
		}
		if err := each(fs, sc.Text()); err != nil {
			return err
		}
	}
	return sc.Err()
}

func codes(s string) (string, error) {
	var b strings.Builder
	for _, h := range strings.Fields(s) {
		v, err := strconv.ParseUint(h, 16, 32)
		if err != nil {
			return "", err
		}
		b.WriteRune(rune(v))
	}
	return b.String(), nil
}

// Generate renders casing_tables.go from the files in dir.
func Generate(dir string) ([]byte, error) {
	lower, upper := map[rune]string{}, map[rune]string{}
	seen := map[string]bool{}
	err := fields(filepath.Join(dir, "SpecialCasing.txt"), func(f []string, line string) error {
		if len(f) < 4 {
			return fmt.Errorf("SpecialCasing.txt: bad line %q", line)
		}
		r, err := codes(f[0])
		if err != nil {
			return err
		}
		if len(f) > 4 && f[4] != "" {
			key := f[0] + "; " + f[4]
			if !conditional[key] {
				return fmt.Errorf("SpecialCasing.txt has a conditional mapping casing.go does not implement: %s", key)
			}
			seen[key] = true
			return nil
		}
		cp := []rune(r)[0]
		lo, err1 := codes(f[1])
		up, err2 := codes(f[3])
		if err1 != nil || err2 != nil {
			return fmt.Errorf("SpecialCasing.txt: bad line %q", line)
		}
		if lo != string(unicode.ToLower(cp)) {
			lower[cp] = lo
		}
		if up != string(unicode.ToUpper(cp)) {
			upper[cp] = up
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for k := range conditional {
		if !seen[k] {
			return nil, fmt.Errorf("SpecialCasing.txt no longer has %s", k)
		}
	}
	fold := map[rune]string{}
	err = fields(filepath.Join(dir, "CaseFolding.txt"), func(f []string, line string) error {
		if len(f) < 3 {
			return fmt.Errorf("CaseFolding.txt: bad line %q", line)
		}
		if f[1] != "C" && f[1] != "F" {
			return nil
		}
		r, err1 := codes(f[0])
		to, err2 := codes(f[2])
		if err1 != nil || err2 != nil {
			return fmt.Errorf("CaseFolding.txt: bad line %q", line)
		}
		fold[[]rune(r)[0]] = to
		return nil
	})
	if err != nil {
		return nil, err
	}
	// The folding differs from Go's simple lowercase mapping where the file
	// folds a code point otherwise, or where Go lowers one the file does
	// not fold.
	folds := map[rune]string{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		want, ok := fold[r]
		if !ok {
			want = string(r)
		}
		if want != string(unicode.ToLower(r)) {
			folds[r] = want
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by casinggen from data/SpecialCasing.txt and data/CaseFolding.txt (Unicode 17.0.0). DO NOT EDIT.\n\npackage stdstrings\n\n")
	table := func(name, doc string, m map[rune]string) {
		fmt.Fprintf(&b, "// %s\nvar %s = caseTable{\n", doc, name)
		keys := make([]rune, 0, len(m))
		for r := range m {
			keys = append(keys, r)
		}
		sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
		for _, r := range keys {
			fmt.Fprintf(&b, "\t{0x%04X, %q},\n", r, m[r])
		}
		b.WriteString("}\n\n")
	}
	table("fullLower", "fullLower is each code point whose full lowercase mapping is not Go's simple one.", lower)
	table("fullUpper", "fullUpper is each code point whose full uppercase mapping is not Go's simple one.", upper)
	table("fullFold", "fullFold is each code point whose full case folding (C and F) is not Go's simple lowercase mapping.", folds)
	return format.Source(b.Bytes())
}

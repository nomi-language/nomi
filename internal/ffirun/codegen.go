// checkProgramVM, runProgramVM and runTestFileVM are the wrapper's modes: nomi
// check's, nomi run's and nomi test's. The VM calls the project's bindings
// through the adapters generated below (nomiHostTable).
func checkProgramVM(entryPath string) {
	if err := nomivmhost.Check(entryPath, nomivmhost.WithHosts(nomiHostTable(entryPath))); err != nil {
		nomivmhost.WriteFailure(stdos.Stderr, err)
		stdos.Exit(1)
	}
}

func runProgramVM(entryPath string, args []string) {
	p, err := nomivmhost.Load(entryPath, nomivmhost.WithHosts(nomiHostTable(entryPath)), nomivmhost.WithInput(stdos.Stdin))
	if err != nil {
		nomivmhost.WriteFailure(stdos.Stderr, err)
		stdos.Exit(1)
	}
	if err := p.RequireMain("run"); err != nil {
		stdfmt.Fprintf(stdos.Stderr, "nomi run: %v\n", err)
		stdos.Exit(1)
	}
	if err := p.Run(stdcontext.Background(), stdos.Stdout, args, true); err != nil {
		if blocked, ok := nomivmhost.IsBlocked(err); ok {
			blocked.Write(stdos.Stderr, nomivmhost.DisplayPath(entryPath))
		} else {
			nomivmhost.WriteFailure(stdos.Stderr, err)
		}
		stdos.Exit(1)
	}
}

// buildImageVM is nomi build's half of the wrapper: lower the entry with the
// project's bindings and write its IR image to args[0], or report what
// nomi run would report and write nothing.
func buildImageVM(entryPath string, args []string) {
	if len(args) < 1 {
		stdfmt.Fprintln(stdos.Stderr, "usage: nomi-ffi-wrapper --nomi-wrapper-mode vmimage <entry.nomi> <image>")
		stdos.Exit(1)
	}
	p, err := nomivmhost.Load(entryPath, nomivmhost.WithHosts(nomiHostTable(entryPath)))
	if err != nil {
		nomivmhost.WriteFailure(stdos.Stderr, err)
		stdos.Exit(1)
	}
	image, usesCompiler, err := p.BuildImage()
	if err != nil {
		if blocked, ok := nomivmhost.IsBlocked(err); ok {
			blocked.Write(stdos.Stderr, nomivmhost.DisplayPath(entryPath))
		} else {
			stdfmt.Fprintln(stdos.Stderr, err)
		}
		stdos.Exit(1)
	}
	if err := stdos.WriteFile(args[0], image, 0o644); err != nil {
		stdfmt.Fprintln(stdos.Stderr, err)
		stdos.Exit(1)
	}
	if usesCompiler {
		stdfmt.Println(imageUsesCompilerMarker)
	}
}

func runTestFileVM(testPath string, args []string, format nomivmhost.TestFormat) {
	opts := nomivmhost.TestOptions{}
	if len(args) > 0 && args[0] != "" {
		line, err := stdstrconv.Atoi(args[0])
		if err != nil {
			stdfmt.Fprintf(stdos.Stderr, "nomi test: invalid line %q\n", args[0])
			stdfmt.Printf("%s %d %d %d\n", ffiTestResultMarker, 0, 1, 0)
			stdos.Exit(1)
		}
		opts.Line = line
		opts.LineSet = true
	}
	rep := nomivmhost.NewTestReportFormat(stdos.Stdout, format)
	// In json mode stdout carries only records, so a case's own output goes
	// to stderr.
	out := stdos.Stdout
	if format == nomivmhost.TestFormatJSON {
		out = stdos.Stderr
	}
	p, err := nomivmhost.Load(testPath, nomivmhost.WithHosts(nomiHostTable(testPath)))
	if err != nil {
		rep.FailFile(testPath, err)
	} else {
		p.Test(out, rep, testPath, opts, func(name string) string { return nomivmhost.TestName(testPath, name) })
	}
	passed, failed := rep.Counts()
	blocked := rep.BlockedCount()
	stdfmt.Printf("%s %d %d %d\n", ffiTestResultMarker, passed, failed, blocked)
	if failed > 0 || blocked > 0 {
		stdos.Exit(1)
	}
}

// wrapperTemplate is the canonical Go source the codegen stage
// emits. It uses only public packages: nomi/vmhost for its three modes
// (check, vmrun, vmtest), with a host table of adapters generated from the
// project's `go` bindings.
//
// The header carries a hash of the template text itself (computed in
// init via SHA256(wrapperTemplate)[0:12]). This hash is recorded in
// the cache's hash.json and used to invalidate the cached wrapper
// when the `nomi` binary is upgraded and ships a new template. The
// header comment doesn't affect compilation; it's a forensic aid
// when staring at a stale wrapper in the cache.
//
// Stable ordering: the Packages range is fed a slice that was sorted
// at discovery time. Combined with deterministic alias assignment,
// the wrapper output is byte-for-byte reproducible across runs given
// the same input — the property the golden test pins down.

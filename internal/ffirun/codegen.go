// templateHash is SHA256(wrapperTemplate)[0:12] — the short version
// embedded in the wrapper header and recorded in hash.json. Computed
// once at init time.
var templateHash = computeTemplateHash()

func computeTemplateHash() string {
	sum := sha256.Sum256([]byte(wrapperTemplate))
	return hex.EncodeToString(sum[:])[:12]
}

// wrapperTmpl is the parsed template, ready for Execute. Parsing
// once at init time keeps codegen on the warm path branch-free.
var wrapperTmpl = template.Must(template.New("wrapper").Funcs(template.FuncMap{
	"funcValue":      wrapperFuncValue,
	"inlineGoBody":   inlineGoBody,
	"lineDirective":  inlineGoLineDirective,
	"quote":          strconv.Quote,
	"returnSuffix":   wrapperReturnSuffix,
	"typePrototype":  wrapperTypePrototype,
	"wrapperImports": wrapperImports,
}).Parse(wrapperTemplate))

// wrapperImports reports whether the generated wrapper must import pkg: every
// discovered package is a user's and its symbols are referenced below, so the
// only package left out is the empty import path a package of purely inline
// `go { }` bodies carries.
func wrapperImports(pkg DiscoveredPackage) bool {
	return pkg.ImportPath != ""
}

// renderWrapper executes the wrapper template with the supplied
// discovered packages and project path, returning the bytes of the
// generated main.go.
//
// The Packages slice is fed in DiscoveredPackage order; callers are
// responsible for having sorted/aliased it before calling. The
// template iterates in slice order, so input order determines output
// order — important for the golden test.
//
// renderWrapper is the bytes-only entry point used by the golden
// test. The cache stage (ensureWrapper, in cache.go) wraps it with
// filesystem I/O.
func renderWrapper(projectPath string, packages []DiscoveredPackage) ([]byte, error) {
	return renderMain(projectPath, packages, mainKind{})
}

// mainKind is which generated main package renderMain writes: the FFI
// wrapper (the zero value), or the project's `nomi build` runner, which
// links nomi/vmrunner instead of nomi/vmhost and so no front end, and
// std/compiler's hosts only when Compiler is set.
type mainKind struct {
	Runner   bool
	Compiler bool
}

func renderMain(projectPath string, packages []DiscoveredPackage, kind mainKind) ([]byte, error) {
	adapters, err := generateAdapters(projectPath, packages)
	if err != nil {
		return nil, fmt.Errorf("generating the VM's host adapters: %w", err)
	}
	data := struct {
		TemplateHash       string
		ProjectPath        string
		Packages           []DiscoveredPackage
		HasGoDecls         bool
		HasInlineGo        bool
		InlineGoHelpers    []InlineGoHelper
		UsesStdTime        bool
		HasEntryScopedKeys bool
		Adapters           *wrapperAdapters
		Runner             bool
		Compiler           bool
	}{
		Runner:             kind.Runner,
		Compiler:           kind.Compiler,
		TemplateHash:       templateHash,
		ProjectPath:        projectPath,
		Packages:           packages,
		HasGoDecls:         wrapperHasGoDecls(packages),
		HasInlineGo:        wrapperHasInlineGo(packages),
		InlineGoHelpers:    InlineGoHelpers,
		UsesStdTime:        wrapperUsesStdTime(packages),
		HasEntryScopedKeys: wrapperHasEntryScopedKeys(packages),
		Adapters:           adapters,
	}
	var buf bytes.Buffer
	if err := wrapperTmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("rendering wrapper template: %w", err)
	}
	out, err := goformat.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting wrapper source: %w", err)
	}
	return out, nil
}

// wrapperHasEntryScopedKeys reports whether any discovered declaration's key
// depends on which file is the entry, which is what decides whether the
// nomiExternKey helper is emitted at all.
//
// Gated so a wrapper with no module-qualified declaration carries no helper it
// never calls.
func wrapperHasEntryScopedKeys(packages []DiscoveredPackage) bool {
	for _, pkg := range packages {
		for _, t := range pkg.Types {
			if t.EntryKey != "" {
				return true
			}
		}
		for _, e := range pkg.Exports {
			if e.EntryKey != "" {
				return true
			}
		}
	}
	return false
}

func wrapperTypePrototype(pkg DiscoveredPackage, typ DiscoveredType) string {
	if typ.GoTypeExpr != "" {
		return "(" + typ.GoTypeExpr + ")(nil)"
	}
	return "(*" + pkg.Alias + "." + typ.TypeName + ")(nil)"
}

func wrapperFuncValue(pkg DiscoveredPackage, exp DiscoveredExport) string {
	if exp.GoBody != "" {
		return exp.WrapperName
	}
	return pkg.Alias + "." + exp.FuncName
}

func wrapperReturnSuffix(ret string) string {
	if ret == "" {
		return ""
	}
	return " " + ret
}

func inlineGoLineDirective(file string, line int) string {
	if file == "" || line <= 0 {
		return ""
	}
	return fmt.Sprintf("//line %s:%d", filepath.ToSlash(file), line)
}

func inlineGoBody(file string, line int, body string) string {
	body = indentGoBody(body)
	directive := inlineGoLineDirective(file, line)
	if directive == "" {
		return body
	}
	if body == "" {
		return directive
	}
	return directive + "\n" + body
}

func indentGoBody(body string) string {
	body = strings.TrimSpace(body)
	if body == "" {
		return ""
	}
	lines := strings.Split(body, "\n")
	for i, line := range lines {
		lines[i] = "\t" + strings.TrimRight(line, " \t")
	}
	return strings.Join(lines, "\n")
}

func wrapperUsesStdTime(packages []DiscoveredPackage) bool {
	for _, pkg := range packages {
		for _, exp := range pkg.Exports {
			if strings.Contains(exp.ParamDecls, "stdtime.") || strings.Contains(exp.ReturnDecl, "stdtime.") {
				return true
			}
		}
	}
	return false
}

func wrapperHasGoDecls(packages []DiscoveredPackage) bool {
	for _, pkg := range packages {
		if len(pkg.GoDecls) > 0 {
			return true
		}
	}
	return false
}

func wrapperHasInlineGo(packages []DiscoveredPackage) bool {
	for _, pkg := range packages {
		for _, exp := range pkg.Exports {
			if exp.GoBody != "" {
				return true
			}
		}
	}
	return false
}

// The go.mod nomi keeps is the header and the module line, written beside a
// nomi.toml with a [module].path, rewritten when it says anything else, and
// never written beside a nomi.toml with no path. GoModProblem says the same
// of the file on disk.
func TestWriteGoMod_KeepsTheModuleLineOfThePath(t *testing.T) {
	const want = "// Generated by nomi from nomi.toml's [module].path. Do not edit.\nmodule example.com/kit/v2\n"
	if got := string(GoModText("example.com/kit/v2")); got != want {
		t.Fatalf("GoModText is\n%s\nwant\n%s", got, want)
	}
	dir := t.TempDir()
	goMod := filepath.Join(dir, GoModName)
	manifest := func(text string) { writeFile(t, filepath.Join(dir, "nomi.toml"), text) }
	problem := func() string {
		t.Helper()
		p, err := GoModProblem(dir)
		if err != nil {
			t.Fatal(err)
		}
		return p
	}
	write := func() bool {
		t.Helper()
		wrote, err := WriteGoMod(dir)
		if err != nil {
			t.Fatal(err)
		}
		return wrote
	}

	// No path: no go.mod, and nothing to say.
	manifest("[module]\nname = \"kit\"\n")
	if write() || problem() != "" {
		t.Fatalf("a module with no path: WriteGoMod wrote, or GoModProblem says %q", problem())
	}
	if _, err := os.Stat(goMod); err == nil {
		t.Fatal("WriteGoMod wrote a go.mod for a module with no path")
	}

	// A path: missing, then written once.
	manifest("[module]\nname = \"kit\"\npath = \"example.com/kit/v2\"\n")
	if p := problem(); !strings.HasPrefix(p, "missing:") || !strings.Contains(p, "`nomi fetch`") {
		t.Fatalf("GoModProblem of a missing go.mod is %q", p)
	}
	if !write() || readFile(t, goMod) != want {
		t.Fatalf("WriteGoMod wrote\n%s", readFile(t, goMod))
	}
	if write() || problem() != "" {
		t.Fatalf("a current go.mod: WriteGoMod wrote again, or GoModProblem says %q", problem())
	}

	// A module line alone that differs or lacks the header, and a go.mod
	// with any other directive, is rewritten: a directory that holds no Go
	// code is no Go module's, so its go.mod is nomi's.
	for _, stale := range []string{
		"module example.com/kit\n",
		"module example.com/kit/v2\n",
		"module example.com/kit/v2\n\ngo 1.27.0\n",
		"module example.com/other\n\nrequire golang.org/x/text v0.37.0\n",
	} {
		writeFile(t, goMod, stale)
		if p := problem(); !strings.Contains(p, "not the file nomi writes for [module].path example.com/kit/v2") {
			t.Fatalf("GoModProblem of %q is %q", stale, p)
		}
		if !write() || readFile(t, goMod) != want {
			t.Fatalf("WriteGoMod over %q wrote\n%s", stale, readFile(t, goMod))
		}
	}

}

// A directory that holds Go code is a Go module's, such as an embedding
// program's: its go.mod is kept as written, or left missing, and
// GoModProblem says nothing about it. A .go file only Go leaves out of the
// module (under testdata, a `.` or `_` directory, or a nested module) makes
// it no Go module's, and nomi keeps its go.mod as before.
func TestWriteGoMod_KeepsTheGoModOfADirectoryWithGoCode(t *testing.T) {
	const embedder = "module example.com/host\n\ngo 1.27.0\n\nrequire github.com/nomi-language/nomi v0.1.0\n"
	setupDir := func(t *testing.T, goFile string, goMod string) string {
		t.Helper()
		dir := t.TempDir()
		writeFile(t, filepath.Join(dir, "nomi.toml"), "[module]\nname = \"host\"\npath = \"example.com/host\"\n")
		writeFile(t, filepath.Join(dir, goFile), "package main\n")
		if goMod != "" {
			writeFile(t, filepath.Join(dir, GoModName), goMod)
		}
		return dir
	}
	for _, goFile := range []string{"main.go", filepath.Join("cmd", "host", "main.go")} {
		for _, goMod := range []string{embedder, ""} {
			dir := setupDir(t, goFile, goMod)
			p, err := GoModProblem(dir)
			if err != nil || p != "" {
				t.Fatalf("%s, go.mod %q: GoModProblem says %q, %v", goFile, goMod, p, err)
			}
			wrote, err := WriteGoMod(dir)
			if err != nil || wrote {
				t.Fatalf("%s, go.mod %q: WriteGoMod wrote %v, %v", goFile, goMod, wrote, err)
			}
			got, err := os.ReadFile(filepath.Join(dir, GoModName))
			if goMod == "" {
				if err == nil {
					t.Fatalf("%s: WriteGoMod wrote a go.mod beside Go code\n%s", goFile, got)
				}
			} else if string(got) != embedder {
				t.Fatalf("%s: WriteGoMod changed the go.mod beside Go code to\n%s", goFile, got)
			}
		}
	}

	// Go code that is not this module's leaves the go.mod nomi's.
	for _, goFile := range []string{
		filepath.Join("testdata", "x.go"),
		filepath.Join(".cache", "x.go"),
		filepath.Join("_old", "x.go"),
	} {
		dir := setupDir(t, goFile, embedder)
		if p, err := GoModProblem(dir); err != nil || !strings.Contains(p, "not the file nomi writes") {
			t.Fatalf("%s: GoModProblem says %q, %v", goFile, p, err)
		}
		if wrote, err := WriteGoMod(dir); err != nil || !wrote || readFile(t, filepath.Join(dir, GoModName)) != string(GoModText("example.com/host")) {
			t.Fatalf("%s: WriteGoMod wrote %v, %v", goFile, wrote, err)
		}
	}
	dir := setupDir(t, filepath.Join("nested", "x.go"), "")
	writeFile(t, filepath.Join(dir, "nested", GoModName), "module example.com/nested\n")
	if wrote, err := WriteGoMod(dir); err != nil || !wrote {
		t.Fatalf("Go code in a nested module: WriteGoMod wrote %v, %v", wrote, err)
	}

	// This repository's root holds Go code only in its packages' directories.
	if goCode, err := holdsGo(filepath.Join("..", "..")); err != nil || !goCode {
		t.Fatalf("holdsGo of the repository's root is %v, %v", goCode, err)
	}
}

// A fetch that writes nomi.lock writes the go.mod too; one that only reads
// writes neither.
func TestFetch_WritesTheGoModWithTheLock(t *testing.T) {
	p := newTestProxy(t)
	publishGreet(t, p, "v0.1.0")
	app, _ := setup(t, p)
	writeFile(t, filepath.Join(app, "nomi.toml"), "[module]\nname = \"app\"\npath = \"example.com/app\"\n\n[dependencies]\n"+
		"greet = { module = \"example.com/greet\", version = \"v0.1.0\" }\n")
	if _, err := Fetch(app, Options{}); err == nil {
		t.Fatal("a fetch that may not update fetched a module nomi.lock does not hold")
	}
	if _, err := os.Stat(filepath.Join(app, GoModName)); err == nil {
		t.Fatal("a fetch that may not update wrote go.mod")
	}
	if _, err := Fetch(app, Options{Update: true}); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, filepath.Join(app, GoModName)); got != string(GoModText("example.com/app")) {
		t.Fatalf("Fetch with Update wrote go.mod\n%s", got)
	}
}

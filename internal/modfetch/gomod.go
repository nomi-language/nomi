package modfetch

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/mod/modfile"

	"github.com/nomi-language/nomi/internal/modcache"
)

// GoModName is the file Go's module proxy reads a module's identity from.
const GoModName = "go.mod"

// goModHeader is the first line of the go.mod nomi writes.
const goModHeader = "// Generated by nomi from nomi.toml's [module].path. Do not edit.\n"

// GoModText is the go.mod nomi writes beside the nomi.toml of a module
// published at path: the header and the `module` line, nothing else. Go's
// module proxy serves a module in a subdirectory of its repository, or at a
// /vN path, only with a go.mod that names it, and leaves a directory with a
// go.mod out of the zip of the module around it.
func GoModText(path string) []byte {
	return []byte(goModHeader + "module " + modfile.AutoQuote(path) + "\n")
}

// goModPlan is what nomi keeps as the go.mod beside root's nomi.toml: its
// file, the text it writes there and the text there now (nil when there is
// none), or keep false when nomi keeps none there.
//
// nomi keeps the go.mod of a nomi.toml with a [module].path whose directory
// holds no Go code, and rewrites one there that says more than its module
// line. A directory that holds Go code (holdsGo) is a Go module's, such as
// an embedding program's or this repository's root, so its go.mod is kept as
// written, or left missing, and nomi says nothing about it. A nomi.toml with
// no path gets no go.mod.
func goModPlan(root string) (file string, want, have []byte, keep bool, err error) {
	mf, err := modcache.ReadModuleFile(root)
	if err != nil || mf == nil || mf.Path == "" {
		return "", nil, nil, false, err
	}
	file = filepath.Join(root, GoModName)
	have, err = os.ReadFile(file)
	switch {
	case errors.Is(err, os.ErrNotExist):
		have = nil
	case err != nil:
		return "", nil, nil, false, err
	}
	want = GoModText(mf.Path)
	if string(have) != string(want) {
		// Only a go.mod nomi would write decides anything, so the tree is
		// walked only when the file there is not that text.
		goCode, err := holdsGo(root)
		if err != nil || goCode {
			return "", nil, nil, false, err
		}
	}
	return file, want, have, true, nil
}

// holdsGo reports whether the Go module rooted at root would hold a .go
// file: one in root or in a directory under it, leaving out what Go leaves
// out of a module (a testdata directory, one whose name starts with `.` or
// `_`, and one with a go.mod of its own, which is a module of its own).
func holdsGo(root string) (bool, error) {
	found := errors.New("found")
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path == root {
				return nil
			}
			name := d.Name()
			if name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") {
				return filepath.SkipDir
			}
			if _, err := os.Stat(filepath.Join(path, GoModName)); err == nil {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(d.Name(), ".go") && d.Type().IsRegular() {
			return found
		}
		return nil
	})
	if errors.Is(err, found) {
		return true, nil
	}
	return false, err
}

// WriteGoMod writes the go.mod nomi keeps beside root's nomi.toml when the
// file there is not that text, and reports whether it wrote. `nomi new`,
// `init`, `add`, `remove`, `update` and `fetch` call it; a fetch calls it
// whenever it writes nomi.lock.
func WriteGoMod(root string) (bool, error) {
	file, want, have, keep, err := goModPlan(root)
	if err != nil || !keep || string(have) == string(want) {
		return false, err
	}
	return true, writeFileAtomic(file, want, 0o644)
}

// GoSumName is the go command's file of module hashes. nomi reads none:
// nomi.lock holds the hashes of a Nomi module's dependencies.
const GoSumName = "go.sum"

// UnreadGoFiles names the files beside root's nomi.toml that nothing reads:
// a go.sum, and a go.mod when nomi.toml has no [module].path, so nomi keeps
// no go.mod there. It names none when the directory holds Go code
// (holdsGo), whose go.mod and go.sum are the go command's. `nomi check`,
// `new`, `init`, `fetch`, `add`, `remove` and `update` say they can be
// deleted; nomi deletes neither.
func UnreadGoFiles(root string) ([]string, error) {
	mf, err := modcache.ReadModuleFile(root)
	if err != nil || mf == nil {
		return nil, err
	}
	var names []string
	if _, err := os.Stat(filepath.Join(root, GoModName)); err == nil && mf.Path == "" {
		names = append(names, GoModName)
	}
	if _, err := os.Stat(filepath.Join(root, GoSumName)); err == nil {
		names = append(names, GoSumName)
	}
	if len(names) == 0 {
		return nil, nil
	}
	if goCode, err := holdsGo(root); err != nil || goCode {
		return nil, err
	}
	return names, nil
}

// GoModProblem says what is wrong with the go.mod beside root's nomi.toml
// and the command that writes it, or "" when it is the one nomi keeps or
// nomi keeps none there. `nomi check` fails with it.
func GoModProblem(root string) (string, error) {
	_, want, have, keep, err := goModPlan(root)
	switch {
	case err != nil || !keep || string(have) == string(want):
		return "", err
	case have == nil:
		return "missing: a module with a [module].path keeps a go.mod that holds only its module line, " +
			"so Go's module proxy serves it; run `nomi fetch` to write it", nil
	}
	return fmt.Sprintf("not the file nomi writes for [module].path %s; run `nomi fetch` to write it",
		modfile.ModulePath(want)), nil
}

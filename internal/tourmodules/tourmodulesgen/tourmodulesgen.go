// Package tourmodulesgen writes internal/tourmodules's modules_sources_gen.go: the
// Nomi sources and embedded files of each module the tour links, read from
// its directory under lib/. See internal/tourmodules.
package tourmodulesgen

import (
	"bytes"
	"fmt"
	goformat "go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/nomi-language/nomi/internal/analysis"
	"github.com/nomi-language/nomi/internal/ast"
	"github.com/nomi-language/nomi/internal/lexer"
	"github.com/nomi-language/nomi/internal/parser"
	"github.com/nomi-language/nomi/internal/tourmodules"
	"github.com/nomi-language/nomi/internal/virtualproject"
)

// GoDir is the folder, under the repository root, of the package whose
// file SourcesFile writes.
const GoDir = "internal/tourmodules"

// render is a generated file's text, formatted.
func render(name string, text []byte) ([]byte, error) {
	formatted, err := goformat.Source(text)
	if err != nil {
		return nil, fmt.Errorf("formatting %s: %w\n%s", name, err, text)
	}
	return formatted, nil
}

// SourcesFileName is the file SourcesFile writes, in internal/tourmodules.
const SourcesFileName = "modules_sources_gen.go"

// SourcesFile is internal/tourmodules's modules_sources_gen.go: the text of each
// tour module's nomi.toml and Nomi files, its tests left out, and the
// files its `embed` declarations name, in base64, read from its directory
// under root. A tour module is its own Go module, nested in this
// repository, so the compiler's module cannot embed its files; the tour's
// wasm carries them from this file.
func SourcesFile(root string) ([]byte, error) {
	var sources, embedded bytes.Buffer
	for _, m := range tourmodules.Modules {
		dir := filepath.Join(root, filepath.FromSlash(m.Dir))
		files, err := ModuleSources(dir)
		if err != nil {
			return nil, fmt.Errorf("the tour module %s: %w", m.Name, err)
		}
		data, err := ModuleEmbedded(dir, files)
		if err != nil {
			return nil, fmt.Errorf("the tour module %s: %w", m.Name, err)
		}
		fmt.Fprintf(&sources, "\t%s: {\n", strconv.Quote(m.Name))
		for _, name := range files {
			text, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&sources, "\t\t%s: %s,\n", strconv.Quote(name), strconv.Quote(string(text)))
		}
		sources.WriteString("\t},\n")
		if len(data) == 0 {
			continue
		}
		fmt.Fprintf(&embedded, "\t%s: {\n", strconv.Quote(m.Name))
		for _, name := range data {
			content, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
			if err != nil {
				return nil, err
			}
			// Base64 holds no backquote, so the body is a raw string.
			fmt.Fprintf(&embedded, "\t\t%s: `%s`,\n", strconv.Quote(name), virtualproject.Base64Body(content))
		}
		embedded.WriteString("\t},\n")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate ./internal/tourmodules; DO NOT EDIT.\n\n")
	out.WriteString("// The nomi.toml and Nomi files of every tour module, its tests left out,\n")
	out.WriteString("// and the files its embeds name, from the module's directory in the tree.\n")
	out.WriteString("// See modules.go.\n\n")
	out.WriteString("package tourmodules\n\n")
	out.WriteString("var moduleSources = map[string]map[string]string{\n")
	out.Write(sources.Bytes())
	out.WriteString("}\n\n")
	out.WriteString("var moduleEmbedded = map[string]map[string]string{\n")
	out.Write(embedded.Bytes())
	out.WriteString("}\n")
	return render(SourcesFileName, out.Bytes())
}

// ModuleEmbedded is the paths, in dir, of the files the `embed`
// declarations of the module's Nomi files sources name, as the front end
// resolves them (analysis.EmbeddedPaths), each once, sorted.
func ModuleEmbedded(dir string, sources []string) ([]string, error) {
	seen := map[string]bool{}
	var out []string
	for _, name := range sources {
		if !strings.HasSuffix(name, ".nomi") {
			continue
		}
		text, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
		if err != nil {
			return nil, err
		}
		nodes, err := parser.Parse(lexer.Lex(string(text)))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		for _, n := range nodes {
			d, ok := n.(*ast.EmbedDecl)
			if !ok {
				continue
			}
			paths, err := analysis.EmbeddedPaths(dir, d)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
			for _, p := range paths {
				if !seen[p] {
					seen[p] = true
					out = append(out, p)
				}
			}
		}
	}
	sort.Strings(out)
	return out, nil
}

// ModuleSources is the paths, in dir, of the files of the Nomi module at
// dir that a program importing it reads: its nomi.toml and its Nomi files,
// not its tests, nor any file under a directory that holds a go.mod or a
// nomi.toml of its own, or whose name starts with `.` or is testdata.
func ModuleSources(dir string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		if d.IsDir() {
			if rel == "." {
				return nil
			}
			if strings.HasPrefix(d.Name(), ".") || d.Name() == "testdata" || isFile(filepath.Join(path, "go.mod")) || isFile(filepath.Join(path, "nomi.toml")) {
				return filepath.SkipDir
			}
			return nil
		}
		name := d.Name()
		if rel == "nomi.toml" || (strings.HasSuffix(name, ".nomi") && !strings.HasSuffix(name, "_test.nomi")) {
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	sort.Strings(out)
	return out, err
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

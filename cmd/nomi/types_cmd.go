const typesUsage = "usage: nomi types <paths...> [-o <file>]"

// errTypesFailed is a `nomi types` run whose check failed and already
// printed its diagnostics.
var errTypesFailed = errors.New("types failed")

// runTypes implements `nomi types <paths...> [-o file]`: TypeScript
// declarations for the public types the named files and directories
// declare that cross as JSON, and every type they reach
// (internal/webtypes), written to stdout or to -o's file.
func runTypes(args []string) error {
	var paths []string
	out := ""
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if v, ok := strings.CutPrefix(arg, "-o="); ok {
			out = v
			continue
		}
		if arg == "-o" {
			if i+1 >= len(args) {
				return fmt.Errorf("nomi types: -o needs a file\n%s", typesUsage)
			}
			i++
			out = args[i]
			continue
		}
		if isFlag(arg) {
			return unknownFlag("nomi types", arg, typesUsage)
		}
		paths = append(paths, arg)
	}
	if len(paths) == 0 {
		return errors.New(typesUsage)
	}
	text, err := typesFor(paths)
	if err != nil {
		return err
	}
	if out == "" {
		_, err = os.Stdout.WriteString(text)
		return err
	}
	if err := os.WriteFile(out, []byte(text), 0o644); err != nil {
		return fmt.Errorf("nomi types: %w", err)
	}
	return nil
}

// typesFor is the declarations file for paths. Each path is a .nomi file,
// or a directory, which names every .nomi file under it, as a directory
// import reaches them. Each file is checked in the programs of its project
// that load it (typesRoots).
func typesFor(paths []string) (string, error) {
	filesOf := make([][]string, len(paths))
	var all []string
	seen := map[string]bool{}
	for i, path := range paths {
		files, err := typesFiles(path)
		if err != nil {
			return "", fmt.Errorf("nomi types: %w", err)
		}
		filesOf[i] = files
		for _, f := range files {
			if !seen[f] {
				seen[f] = true
				all = append(all, f)
			}
		}
	}
	sort.Strings(all)
	roots, err := typesRoots(all)
	if err != nil {
		return "", fmt.Errorf("nomi types: %w", err)
	}
	w := webtypes.NewWriter(webtypes.IntsNumber)
	for _, root := range roots {
		prog, err := irbuild.AnalyzeFile(root, frontend.Config{})
		if err != nil {
			if ownLines(err) {
				vmhost.WriteFailure(os.Stderr, err)
				return "", errTypesFailed
			}
			return "", fmt.Errorf("nomi types: %s: %w", vmhost.DisplayPath(root), err)
		}
		w.AddProgram(webtypes.ModulesOf(prog))
	}
	for i, path := range paths {
		n := 0
		for _, f := range filesOf[i] {
			n += w.AddFile(f)
		}
		if n == 0 {
			what := path + " declares no"
			if info, err := os.Stat(path); err == nil && info.IsDir() {
				what = "no file under " + path + " declares a"
			}
			return "", fmt.Errorf("nomi types: %s pub type that crosses as JSON\nhelp: derive ToJson or FromJson for a pub struct, enum or distinct type", what)
		}
	}
	w.Seal()
	var b strings.Builder
	named := make([]string, len(paths))
	for i, p := range paths {
		named[i] = filepath.ToSlash(p)
	}
	fmt.Fprintf(&b, "// Generated by `nomi types %s`. Do not edit.\n", strings.Join(named, " "))
	b.WriteString("//\n")
	b.WriteString("// The JSON each type's ToJson writes. An Int is a number, exact up to 2^53;\n")
	b.WriteString("// send one that may be larger as a String.\n\n")
	b.WriteString(strings.TrimSuffix(w.Declarations(), "\n"))
	return b.String(), nil
}

// typesRoots is the programs files are checked in, as `nomi check` checks
// their project (discoverCheckFiles): each program of the project, of the
// project root analysis.ProjectRoot finds for each file, that loads one of
// files, so a file that reads an application field is checked under the
// entry whose boot returns the application. A file no program of its
// project loads is checked as before, through another of files that
// imports it or on its own (programRoots).
func typesRoots(files []string) ([]string, error) {
	named := map[string]bool{}
	for _, f := range files {
		named[f] = true
	}
	projects := map[string]bool{}
	reached := map[string]bool{}
	seen := map[string]bool{}
	var roots []string
	for _, f := range files {
		if _, _, ok := frontend.StdlibFile(f); ok {
			continue
		}
		dir := analysis.ProjectRoot(f, "")
		if projects[dir] {
			continue
		}
		projects[dir] = true
		programs, _, _, err := discoverCheckFiles(dir)
		if err != nil {
			return nil, err
		}
		for _, p := range programs {
			loads := []string{p}
			if imported, err := frontend.ImportedFiles(p); err == nil {
				loads = append(loads, imported...)
			}
			reaches := false
			for _, l := range loads {
				if named[l] {
					reached[l] = true
					reaches = true
				}
			}
			if reaches && !seen[p] {
				seen[p] = true
				roots = append(roots, p)
			}
		}
	}
	var rest []string
	for _, f := range files {
		if !reached[f] {
			rest = append(rest, f)
		}
	}
	if len(rest) > 0 {
		own, _ := programRoots(rest)
		for _, r := range own {
			if !seen[r] {
				seen[r] = true
				roots = append(roots, r)
			}
		}
	}
	sort.Strings(roots)
	return roots, nil
}

// typesFiles is the .nomi files path names, absolute and sorted: path
// itself, or every one under a directory but those of another module (a
// directory holding its own nomi.toml).
func typesFiles(path string) ([]string, error) {
	info, err := os.Stat(path)
	if err != nil {
		return nil, pathError(path, err)
	}
	if !info.IsDir() {
		if filepath.Ext(path) != ".nomi" {
			return nil, fmt.Errorf("%s is not a .nomi file or a directory", path)
		}
		abs, err := filepath.Abs(path)
		if err != nil {
			return nil, err
		}
		return []string{abs}, nil
	}
	var files []string
	err = filepath.WalkDir(path, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "node_modules", "dist", ".astro":
				return filepath.SkipDir
			}
			if p != path {
				if _, err := os.Stat(filepath.Join(p, "nomi.toml")); err == nil {
					return filepath.SkipDir
				}
			}
			if stdFixturesDir(p) {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(p) != ".nomi" {
			return nil
		}
		abs, err := filepath.Abs(p)
		if err != nil {
			return err
		}
		files = append(files, abs)
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("%s holds no .nomi file", path)
	}
	sort.Strings(files)
	return files, nil
}

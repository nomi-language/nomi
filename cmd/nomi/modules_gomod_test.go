// A module of Nomi alone is published through Go's module proxy with the
// go.mod nomi writes beside its nomi.toml, which holds only its module
// line: `nomi init` and `nomi fetch` write it, the proxy's zips are built
// from the directories as Go builds them (modzip.CreateFromDir), a module
// in a subdirectory of its repository and a /v2 module are served from
// them, and a consumer adds, fetches and runs both. The repository's root
// module's zip leaves the subdirectory module out, because of that go.mod.
func TestModules_AGeneratedGoModPublishesSubdirectoryAndMajorVersionModules(t *testing.T) {
	c := newModuleCLI(t)
	tmp := t.TempDir()
	proxy := c.proxy
	must := c.must
	header := "// Generated by nomi from nomi.toml's [module].path. Do not edit.\n"

	// A repository whose root is a module and whose kit/ is another.
	repo := filepath.Join(tmp, "repo")
	mustWrite(t, filepath.Join(repo, "repo.nomi"), "pub fn name() -> String\n    \"repo\"\nend\n")
	if out := must(repo, "init", "example.com/repo"); out != "wrote nomi.toml and go.mod" {
		t.Fatalf("nomi init printed %q", out)
	}
	kit := filepath.Join(repo, "kit")
	mustWrite(t, filepath.Join(kit, "nomi.toml"), "[module]\nname = \"kit\"\npath = \"example.com/repo/kit\"\n")
	mustWrite(t, filepath.Join(kit, "kit.nomi"), "pub fn hello(name: String) -> String\n    \"hello, ${name}\"\nend\n")
	must(kit, "fetch")
	// A /v2 module at the root of its own repository.
	greet := filepath.Join(tmp, "greet")
	mustWrite(t, filepath.Join(greet, "nomi.toml"), "[module]\nname = \"greet\"\npath = \"example.com/greet/v2\"\n")
	mustWrite(t, filepath.Join(greet, "greet.nomi"), "pub fn shout(s: String) -> String\n    String.uppercase(s)\nend\n")
	must(greet, "fetch")

	for dir, path := range map[string]string{repo: "example.com/repo", kit: "example.com/repo/kit", greet: "example.com/greet/v2"} {
		data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err != nil {
			t.Fatal(err)
		}
		if want := header + "module " + path + "\n"; string(data) != want {
			t.Errorf("%s/go.mod is\n%s\nwant\n%s", dir, data, want)
		}
	}

	zipOf := func(dir string, m module.Version) []byte {
		t.Helper()
		var buf bytes.Buffer
		if err := modzip.CreateFromDir(&buf, m, dir); err != nil {
			t.Fatalf("zipping %s as %s: %v", dir, m, err)
		}
		return buf.Bytes()
	}
	names := func(data []byte) []string {
		t.Helper()
		r, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
		if err != nil {
			t.Fatal(err)
		}
		var out []string
		for _, f := range r.File {
			out = append(out, f.Name)
		}
		return out
	}
	publish := func(dir string, m module.Version) {
		t.Helper()
		goMod, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err != nil {
			t.Fatal(err)
		}
		publishZip(t, proxy, m.Path, m.Version, string(goMod), zipOf(dir, m))
	}
	root := module.Version{Path: "example.com/repo", Version: "v1.0.0"}
	for _, name := range names(zipOf(repo, root)) {
		if strings.HasPrefix(name, "example.com/repo@v1.0.0/kit/") {
			t.Errorf("the root module's zip holds %s, a file of the module in kit/", name)
		}
	}
	// Without its go.mod, kit/ is a directory of the root module.
	saved, _ := os.ReadFile(filepath.Join(kit, "go.mod"))
	if err := os.Remove(filepath.Join(kit, "go.mod")); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(strings.Join(names(zipOf(repo, root)), " "), "example.com/repo@v1.0.0/kit/kit.nomi") {
		t.Errorf("with no go.mod in kit/, the root module's zip still leaves kit/ out, so the go.mod is not what leaves it out")
	}
	mustWrite(t, filepath.Join(kit, "go.mod"), string(saved))
	publish(repo, root)
	publish(kit, module.Version{Path: "example.com/repo/kit", Version: "v1.0.0"})
	publish(greet, module.Version{Path: "example.com/greet/v2", Version: "v2.0.0"})

	app := filepath.Join(tmp, "app")
	mustWrite(t, filepath.Join(app, "nomi.toml"), "[module]\nname = \"app\"\nentry_points = [\"main\"]\n")
	mustWrite(t, filepath.Join(app, "main.nomi"), "import\n    std::io\n    greet\n    kit\nend\n\nfn main()\n    io.print(greet.shout(kit.hello(\"you\")))\nend\n")
	must(app, "add", "example.com/repo/kit@v1.0.0")
	must(app, "add", "example.com/greet/v2")
	toml, err := os.ReadFile(filepath.Join(app, "nomi.toml"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		`kit = { module = "example.com/repo/kit", version = "v1.0.0" }`,
		`greet = { module = "example.com/greet/v2", version = "v2.0.0" }`,
	} {
		if !strings.Contains(string(toml), want) {
			t.Errorf("nomi.toml does not hold %s:\n%s", want, toml)
		}
	}
	if out := must(app, "run", "main.nomi"); out != "HELLO, YOU" {
		t.Fatalf("nomi run printed %q, want HELLO, YOU", out)
	}
	if _, err := os.Stat(filepath.Join(app, "go.mod")); err == nil {
		t.Errorf("nomi wrote a go.mod for a module with no [module].path")
	}
}

// `nomi new` writes the go.mod nomi keeps, and `nomi check` fails, naming
// `nomi fetch`, while that go.mod is missing or names another path.
func TestCheck_FailsOnAGoModNomiWouldWriteOtherwise(t *testing.T) {
	c := newModuleCLI(t)
	tmp := t.TempDir()
	nomi := c.run
	if out, stderr, err := nomi(tmp, "new", "example.com/checked"); err != nil || !strings.Contains(out, "checked/go.mod") {
		t.Fatalf("nomi new: %v\n%s\n%s", err, out, stderr)
	}
	dir := filepath.Join(tmp, "checked")
	goMod := filepath.Join(dir, "go.mod")
	passes := func(why string) {
		t.Helper()
		if out, stderr, err := nomi(dir, "check", "."); err != nil {
			t.Fatalf("nomi check %s: %v\n%s\n%s", why, err, out, stderr)
		}
	}
	fails := func(why, want string) {
		t.Helper()
		out, stderr, err := nomi(dir, "check", ".")
		if err == nil || !strings.Contains(stderr, "FAIL go.mod: "+want) || !strings.Contains(stderr, "run `nomi fetch` to write it") {
			t.Fatalf("nomi check %s: %v, want a failure saying %q and naming `nomi fetch`:\n%s\n%s", why, err, want, out, stderr)
		}
		out, _, err = nomi(dir, "check", "--format", "json", ".")
		if err == nil || !strings.Contains(out, `go.mod","status":"failed"`) {
			t.Fatalf("nomi check --format json %s: %v, want go.mod failed:\n%s", why, err, out)
		}
	}
	passes("after nomi new")

	manifest := filepath.Join(dir, "nomi.toml")
	data, err := os.ReadFile(manifest)
	if err != nil {
		t.Fatal(err)
	}
	mustWrite(t, manifest, strings.Replace(string(data), "example.com/checked", "example.com/checked/v2", 1))
	fails("after the path changed", "not the file nomi writes for [module].path example.com/checked/v2")
	if out, stderr, err := nomi(dir, "fetch"); err != nil {
		t.Fatalf("nomi fetch: %v\n%s\n%s", err, out, stderr)
	}
	passes("after nomi fetch")

	if err := os.Remove(goMod); err != nil {
		t.Fatal(err)
	}
	fails("with no go.mod", "missing")

	// A go.mod that says more than its module line is nomi's while the
	// directory holds no Go code, and a Go module's once it does: check
	// leaves that one alone.
	mustWrite(t, goMod, "module example.com/checked/v2\n\ngo 1.27.0\n")
	fails("with a go line and no Go code", "not the file nomi writes for [module].path example.com/checked/v2")
	mustWrite(t, filepath.Join(dir, "cmd", "host", "main.go"), "package main\n\nfunc main() {}\n")
	passes("with a go.mod of Go code")
}

// A go.mod and go.sum beside a nomi.toml in a directory with no Go code are
// read by nothing, and the commands say so in one line, once, without
// deleting them: both files when nomi.toml has no [module].path, and go.sum
// beside the go.mod nomi rewrites for one with a path. A directory with Go
// code keeps both for the go command, and nothing is said.
func TestModules_SaysWhichGoFilesNothingReads(t *testing.T) {
	c := newModuleCLI(t)
	work := t.TempDir()
	oldGoMod := "module example.com/app\n\ngo 1.24\n\nrequire example.com/kit v1.0.0\n\nreplace example.com/kit => ../kit\n"
	goSum := "example.com/kit v1.0.0 h1:x=\n"
	notes := func(stderr string) []string {
		var out []string
		for _, line := range strings.Split(stderr, "\n") {
			if strings.HasPrefix(line, "note: ") {
				out = append(out, line)
			}
		}
		return out
	}
	says := func(dir, want string, args ...string) {
		t.Helper()
		out, stderr, err := c.run(dir, args...)
		if err != nil {
			t.Fatalf("nomi %s: %v\n%s\n%s", strings.Join(args, " "), err, out, stderr)
		}
		if got := notes(stderr); want == "" && len(got) != 0 || want != "" && (len(got) != 1 || got[0] != want) {
			t.Errorf("nomi %s noted %q, want %q", strings.Join(args, " "), got, want)
		}
	}

	app := filepath.Join(work, "app")
	mustWrite(t, filepath.Join(app, "nomi.toml"), "[module]\nname = \"app\"\nentry_points = [\"main\"]\n")
	mustWrite(t, filepath.Join(app, "main.nomi"), "fn main()\nend\n")
	mustWrite(t, filepath.Join(app, "go.mod"), oldGoMod)
	mustWrite(t, filepath.Join(app, "go.sum"), goSum)
	both := "note: go.mod and go.sum are not read: nomi.toml and nomi.lock hold this module's dependencies, and it has no Go code, so they can be deleted"
	says(app, both, "check", ".")
	says(app, both, "check", "main.nomi")
	says(app, both, "fetch")
	if got := mustRead(t, filepath.Join(app, "go.mod")); got != oldGoMod {
		t.Errorf("go.mod of a module with no [module].path was changed:\n%s", got)
	}
	if got := mustRead(t, filepath.Join(app, "go.sum")); got != goSum {
		t.Errorf("go.sum was changed:\n%s", got)
	}
	mustWrite(t, filepath.Join(app, "cmd", "host", "main.go"), "package main\n\nfunc main() {}\n")
	says(app, "", "check", ".")

	published := filepath.Join(work, "published")
	mustWrite(t, filepath.Join(published, "nomi.toml"), "[module]\nname = \"published\"\npath = \"example.com/published\"\nentry_points = [\"main\"]\n")
	mustWrite(t, filepath.Join(published, "main.nomi"), "fn main()\nend\n")
	mustWrite(t, filepath.Join(published, "go.mod"), oldGoMod)
	mustWrite(t, filepath.Join(published, "go.sum"), goSum)
	sum := "note: go.sum is not read: nomi.toml and nomi.lock hold this module's dependencies, and it has no Go code, so it can be deleted"
	says(published, sum, "fetch")
	if got, want := mustRead(t, filepath.Join(published, "go.mod")), "// Generated by nomi from nomi.toml's [module].path. Do not edit.\nmodule example.com/published\n"; got != want {
		t.Errorf("nomi fetch wrote go.mod\n%s\nwant\n%s", got, want)
	}
	if got := mustRead(t, filepath.Join(published, "go.sum")); got != goSum {
		t.Errorf("go.sum was changed:\n%s", got)
	}
	says(published, sum, "check", ".")
}
